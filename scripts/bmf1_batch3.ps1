## Ponte com a Clínica

Na isquemia miocárdica, o cardíaco fica privado de O₂ e ATP — e sem ATP, as pontes cruzadas de miosina não se desprendem da actina (rigor). O coração pós-infarto com rigidez de parede é a versão patológica desse mecanismo. A troponina I e T sérica (liberadas quando a fibra cardíaca se rompe) são os biomarcadores de infarto — e sua lógica vem diretamente da ultraestrutura: quando a membrana da fibra cardíaca se rompe, as proteínas do sarcômero vazam para o sangue.

