## Relevância Clínica e Acadêmica

A histologia do tecido muscular não é só teoria de lâminas — ela explica diretamente as doenças musculares. A distrofia muscular de Duchenne é uma doença da distrofina (proteína da membrana do sarcolema ligada ao citoesqueleto). A miopatia mitocondrial afeta a função das mitocôndrias da fibra muscular. Para entender essas doenças, você precisa saber a ultraestrutura do músculo. A Uninove cobra principalmente a comparação entre os 3 tipos musculares e os componentes do sarcômero.

---

## 1. Fibra Muscular Esquelética — Ultraestrutura

| Estrutura | Correspondência funcional |
|-----------|--------------------------|
| **Sarcolema** | Membrana plasmática + lâmina basal; contém receptores de acetilcolina |
| **Sarcoplasma** | Citoplasma; rico em glicogênio e mioglobina |
| **Retículo sarcoplasmático** | RE liso especializado em armazenar e liberar Ca²⁺ |
| **Túbulos T** | Invaginações do sarcolema; transmitem o potencial de ação ao interior da fibra |
| **Miofibrilas** | Conjunto de sarcômeros; as "colunas" contrácteis |

---

## 2. O Sarcômero — Unidade Funcional

O **sarcômero** é delimitado por 2 linhas Z. Componentes:

| Estrutura | Filamento | Descrição |
|-----------|-----------|-----------|
| **Linha Z** | — | Ancora filamentos de actina |
| **Filamento fino** | Actina (+ tropomiosina + troponina) | I band (claro) |
| **Filamento grosso** | Miosina II | A band (escuro) |
| **Zona H** | Miosina apenas | Centro do sarcômero; desaparece na contração |
| **Linha M** | — | Centro dos filamentos de miosina |
| **Banda I** | Actina apenas | Claro; diminui na contração |
| **Banda A** | Actina + miosina | Escuro; NÃO muda no comprimento |

> **Regra de ouro:** na contração — banda I diminui, zona H diminui, banda A permanece igual.

### Proteínas regulatórias

| Proteína | Função |
|----------|--------|
| **Tropomiosina** | Bloqueia sítio ativo da actina em repouso |
| **Troponina** | Complexo TnT+TnI+TnC: TnC liga Ca²⁺ → expõe sítio ativo |
| **Titina** | Liga miosina à linha Z; elasticidade passiva do sarcômero |

---

## 3. Comparação Histológica dos 3 Tipos Musculares

| Característica | Esquelético | Cardíaco | Liso |
|----------------|-------------|----------|------|
| Estriação | Sim | Sim | Não |
| Núcleos | Múltiplos, periféricos | 1-2, centrais | 1, central |
| Discos intercalares | Não | **Sim** | Não |
| Mitocôndrias | Moderadas-abundantes (tipo I) | **Abundantíssimas** | Poucas |
| Retículo sarcoplasmático | Bem desenvolvido | Moderado | Pouco desenvolvido |
| Túbulos T | Diáde (1 T + 1 RS) em mamíferos: tríade (1 T entre 2 RS) | Díade | Ausentes (caveolas) |
| Actina/miosina | Filamentos organizados em sarcômeros | Organizados | **Desorganizados** — explica ausência de estriação |
| Discos intercalares | — | Desmossomos + gap junctions (sincício funcional) | — |

---

## 4. Tipos de Fibras Musculares Esqueléticas

| Tipo | Metabolismo | Velocidade | Resistência | Cor | Exemplo |
|------|-------------|------------|-------------|-----|---------|
| **Tipo I** (lenta oxidativa) | Aeróbico | Lenta | Alta (anti-fadiga) | Vermelha (mioglobina) | Sóleo, paraespinhais posturais |
| **Tipo IIa** (rápida oxidativa-glicolítica) | Misto | Rápida | Intermedia | Rósea | Gastrocnêmio |
