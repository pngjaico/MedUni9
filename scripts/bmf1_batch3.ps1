## 1. Componentes do Músculo Esquelético

| Componente | Descrição |
|------------|-----------|
| **Epimísio** | Tecido conjuntivo denso que envolve o músculo inteiro |
| **Perimísio** | Divide o músculo em fascículos (feixes) |
| **Endomísio** | Envolve cada fibra muscular individualmente |
| **Tendão** | Transmite força do músculo ao osso (colágeno I) |
| **Aponeurose** | Tendão em forma de lâmina (ex: aponeurose palmar) |

