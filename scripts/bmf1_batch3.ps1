## Relevância Clínica e Acadêmica

O sistema muscular esquelético é o maior órgão do corpo (~40% da massa corporal em homens). Classificar músculos por forma, função e arquitetura de fibras é essencial para entender por que o bíceps tem mais força de flexão do que extensão, ou por que músculos penados são mais fortes mas produzem menos deslocamento. A Uninove cobra nomenclatura, classificação, origem/inserção e ação muscular — especialmente dos músculos dos membros superiores, inferiores e da coluna.

