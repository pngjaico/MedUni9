## Erros Clássicos em Prova (Uninove)

- **Banda A muda de comprimento na contração:** errado — banda A permanece constante. Banda I e zona H diminuem.
- **Troponina libera o sítio ativo de actina sem Ca²⁺:** em repouso, tropomiosina bloqueia o sítio. A troponina C precisa ligar Ca²⁺ para mover a tropomiosina.
- **Discos intercalares = desmo + gap junctions:** correto para o cardíaco — mas cuidado com a função: desmossomo transmite força mecânica; gap junction passa íon Ca²⁺ (acopla eletricamente o sincício cardíaco).
- **Músculo liso tem sarcômeros:** não tem sarcômeros — filamentos de actina/miosina presentes mas desorganizados, por isso não há estriação.
- **Fibra Tipo I = forte e rápida:** Tipo I é lenta e resistente (aeróbica). Força máxima = Tipo IIb (rápida, anaeróbica).

