## Erros Clássicos em Prova (Uninove)

- **Deltóide = abdução apenas:** fibras anteriores flexionam, médias abduzem, posteriores estendem o ombro.
- **Supraespinhal abduz o ombro inteiro:** supraespinhal faz apenas os primeiros 0-15° de abdução; acima disso é o deltóide.
- **Bíceps só flete o cotovelo:** bíceps também faz supinação do antebraço — é uma de suas ações principais.
- **Tríceps tem 4 cabeças:** tríceps tem 3 cabeças (TRI = 3): longa, lateral e medial.
- **Quadríceps flete o joelho:** quadríceps é EXTENSOR do joelho (e o reto femoral também flete o quadril). Isquiotibiais FLEXIONAM o joelho.

