## Relevância Clínica e Acadêmica

A nota SOAP (Subjetivo, Objetivo, Avaliação, Plano) é o formato de documentação clínica mais utilizado em hospitais, ambulatórios e prontuários eletrônicos de todo o mundo. Saber estruturar uma nota SOAP correta para um paciente musculoesquelético demonstra domínio do método clínico, facilita a comunicação entre profissionais e protege legalmente o médico. Casos clínicos com SOAP aparecem constantemente nas provas práticas e nas simulações de internato da Uninove — dominá-los é diferenciar-se.

---

## 1. Estrutura SOAP

| Componente | O que registra | Exemplo |
|------------|---------------|---------|
| **S — Subjetivo** | O que o paciente relata (queixas, história, sintomas) | "Dor no joelho direito, pior ao subir escadas, há 4 meses" |
| **O — Objetivo** | Dados mensuráveis (sinais vitais, exame físico, exames) | "PA 130/80, FC 78, Joelho D: crepitação medial, sem derrame, ADM preservada, Lachman –" |
| **A — Avaliação** | Diagnóstico(s) ou hipótese(s) | "Gonartrose direita grau II (CID M17)" |
| **P — Plano** | Conduta: exames, tratamentos, encaminhamento, retorno | "RX joelho AP/perfil/axial. Dipirona 1g 6/6h se dor. Fisioterapia. Retorno 6 semanas." |

