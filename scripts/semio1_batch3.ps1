## Relevância Clínica e Acadêmica

O ambulatório real difere do simulado: pacientes chegam com queixas mal definidas, com várias comorbidades, ansiedade e expectativas sobre diagnóstico e pedidos de exame. O médico precisa conduzir a consulta musculoesquelética de forma eficiente no tempo disponível (10-15 min), priorizar os achados mais relevantes e decidir entre observar, tratar empiricamente ou investigar. Na Uninove, questões sobre conduta correta em contexto ambulatorial aparecem muito nas provas práticas e nas simulações de internato.

---

## 1. Estrutura da Consulta Ambulatorial Musculoesquelética

| Fase | Tempo sugerido | Foco prático |
|------|----------------|-------------|
| **Recepção e queixa principal** | 1-2 min | Não interromper; deixar o paciente falar ~30-60 seg |
| **Anamnese dirigida** | 4-5 min | OLDCART + padrão inflamatório/mecânico + sistêmico |
| **Exame físico direcionado** | 3-5 min | Foco na articulação-problema + exame neurológico se irradiação |
| **Síntese e hipótese** | 1 min | Comunicar ao paciente de forma clara |
| **Conduta e plano** | 2-3 min | Exames, tratamento inicial, orientações, retorno |

---

## 2. Armadilhas do Ambulatório Real

### Paciente com múltiplas queixas:
- Não tente resolver tudo em uma consulta
- Priorize a queixa principal (mais grave ou mais funcional)
- Agende retorno para as demais

### Paciente que "pede o exame" antes do exame físico:
- "Doutora, preciso de uma ressonância do joelho" → realizar o exame físico completo ANTES de decidir o exame
- RX é suficiente para maioria das queixas crônicas (artrose, fratura de estresse, alinhamento)
- RNM indicada: suspeita de ruptura ligamentar, lesão meniscal, tumor, infecção profunda

### Paciente com dor crônica + exames normais:
- Investigar fibromialgia, depressão, somatização
- NÃO pedir baterias extensas de exames "para não deixar passar nada" — aumenta ansiedade e custos sem benefício

