## Erros Clássicos em Prova (Uninove)

- **"Se o exame é normal, o paciente não tem nada":** exames normais NÃO significam ausência de doença. Fibromialgia, lombalgia muscular e tendinites iniciais têm exames normais mas causam sofrimento real.
