## Erros Clássicos em Prova (Uninove)

- **"SOAP = só anamnese detalhada":** SOAP tem 4 partes distintas. O componente O (Objetivo) inclui sinais vitais e exame físico — não confundir com a anamnese (S).
- **"Iniciar alopurinol na crise de gota":** alopurinol na crise aguda mobiliza cristais de urato → piora a crise. Iniciar alopurinol só APÓS resolução da crise (mínimo 2-4 semanas) e de forma gradual.
- **"Lasègue positivo = hérnia de disco confirmada":** Lasègue positivo indica irritação do nervo ciático (sensibilidade ~80%), mas não confirma hérnia — pode ser tumor, abscesso, espondilolistese. RNM confirma.
- **"Toda artrite com FR positivo = AR":** FR positivo em baixo título ocorre em infecções, idosos saudáveis e outras doenças. Anti-CCP tem maior especificidade para AR. O diagnóstico é CLÍNICO (critérios ACR/EULAR 2010).
- **"No SOAP, plano = apenas pedir exames":** plano inclui: tratamento (medicação + dose + posologia), orientações não farmacológicas, encaminhamentos e RETORNO definido.

