## Relevância Clínica e Acadêmica

O OSCE (Objective Structured Clinical Examination) é o formato de avaliação prática adotado por universidades médicas e residências para avaliar habilidades clínicas. Saber "montar" uma estação de OSCE musculoesquelético exige que você conheça o que será avaliado em cada etapa (anamnese estruturada, sequência de exame, testes corretos, comunicação com o paciente). A Uninove aplica avaliações práticas progressivas — quem entende o formato do OSCE antecipa o raciocínio da banca avaliadora e executa melhor.

