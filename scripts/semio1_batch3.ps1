## Erros Clássicos em Prova (Uninove)

- **"No OSCE posso começar qualquer etapa na ordem que preferir":** a sequência anamnese → inspeção → palpação → ADM → testes especiais é avaliada na ordem e perde pontos se invertida.
- **"Hemartrose = apenas contusão":** hemartrose aguda pós-trauma de joelho = lesão intra-articular séria (LCA, fratura osteocondral, menisco com vascularização). Deve-se realizar punção (artrocentese) se volumosa, para alívio e análise do líquido.
- **"Fazer todos os testes especiais conhecidos":** OSCE avalia raciocínio clínico. Realizar 15 testes para um caso de impacto de ombro demonstra falta de hipótese diagnóstica — e toma tempo da estação.
- **"RNM é sempre o primeiro exame":** RX simples é o exame inicial na maioria dos problemas musculoesqueléticos. RNM fica para casos onde RX e US não são suficientes (ligamentos, medula, cartilagem).

