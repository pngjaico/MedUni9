## 1. Estrutura de uma Estação OSCE Musculoesquelético

| Etapa | Tempo típico | O que é avaliado |
|-------|-------------|-----------------|
| **Leitura do caso** | 1-2 min | Compreensão da queixa principal |
| **Anamnese** | 4-6 min | OLDCART + padrão inflamatório/mecânico + sistêmico |
| **Exame físico direcionado** | 4-6 min | Sequência: inspeção → palpação → ADM → testes especiais |
| **Diagnóstico sindrômico** | 1-2 min | O que você encontrou, hipótese diagnóstica |
