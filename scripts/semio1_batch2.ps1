## Erros Clássicos em Prova (Uninove)

- **"Lasègue positivo = lesão de LCA":** Lasègue avalia radiculopatia lombar (ciático); LCA é avaliado pelo teste de Lachman. São regiões anatômicas completamente diferentes.
- **"Gaveta anterior é mais sensível que Lachman":** é o contrário — Lachman (joelho em 20-30° flexão) é MAIS SENSÍVEL para LCA que a gaveta anterior (joelho a 90°).
- **"Phalen positivo em qualquer dedo":** a síndrome do túnel do carpo causa parestesia nos dedos 1-4 (polegar, indicador, médio e metade do anelar) — inervação do n. mediano. Dedo mínimo = n. ulnar (não TC).
- **"FABER = teste de ligamento do joelho":** FABER avalia o quadril e a articulação sacroilíaca, não o joelho. É a posição do "4" com o paciente deitado.
- **"ADM ativa maior que passiva impossível":** ADM ativa > passiva indica hipermobilidade articular (síndrome de Ehlers-Danlos). ADM passiva > ativa sugere fraqueza muscular ou ruptura. Ambas as diferenças são clinicamente importantes.

