## 4. Sinal da Tecla Patelar (Derrame de Joelho)

**Técnica:** paciente em decúbito dorsal, joelho estendido. Com uma mão, comprimir as bolsas suprapatelar e parapatelares, deslocando o líquido para a bolsa central. Com o dedo indicador, pressionar rapidamente a patela. Resultado positivo: patela "dança" (afunda e retorna) → líquido presente no joelho.

**Diagnóstico diferencial do derrame de joelho:**
- Hemartrose (trauma = LCA, fratura)
- Derrame sinovial (AR, artrite reativa, artrose avançada)
- Artrite séptica (líquido turvo, febre, urgência!)

---

## Erros Clássicos em Prova (Uninove)

- **"Crepitação = fratura":** crepitação articular fina é sinal de degeneração cartilaginosa (artrose), não de fratura. Crepitação em fratura é grossa, dolorosa e diferente ao tato.
- **"Sinal da tecla patelar positivo = ruptura de LCA":** sinal da tecla patelar indica DERRAME no joelho, não ruptura de LCA. Para LCA usa-se teste de Lachman e gaveta anterior.
- **"Bursite é a mesma coisa que artrite":** bursite é inflamação da bursa (fora da articulação); artrite é inflamação intra-articular (sinovial). A localização anatômica da dor/inchaço as distingue.
- **"Palpar a parte dolorida primeiro":** a sequência correta começa pelo contralateral ou por região indolor — reduz defesa muscular e ansiedade do paciente, melhorando a qualidade do exame.
- **"Cisto de Baker é tumor":** cisto de Baker é uma coleção poplítea de líquido sinovial que herniou pela cápsula posterior do joelho — consequência de derrame crônico (artrose, AR). Não é neoplasia.

