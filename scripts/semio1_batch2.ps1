## Relevância Clínica e Acadêmica

A palpação transforma hipóteses em diagnósticos. Identificar um ponto de Gatilho miofascial, um derrame articular, um crepito patelofemoral ou a instabilidade ligamentar do tornozelo exige mãos treinadas e conhecimento anatômico preciso. Na prática ambulatorial e hospitalar, a palpação correta economiza pedidos de imagem e direciona o tratamento. Na prova, você será testado sobre quais pontos palpar e o que esperar encontrar em cada patologia — o "onde dói com palpação" é um dado clínico, não uma curiosidade.

---

## 1. Princípios da Palpação Musculoesquelética

- **Sequência:** palpar após inspecionar (não crie achados antes de ver)
- **Palpação leve → profunda:** começar sem pressão, aumentar gradualmente
- **Comparar bilateralmente:** temperatura, consistência, volume
- **Palpar longe da queixa primeiro:** aborda o lado contralateral antes do doloroso (reduz defesa muscular)
- **Temperatura:** dorso dos dedos é mais sensível para calor (artrite ativa, infecção)

---

## 2. Achados Palpáveis por Estrutura

| Estrutura | O que se palpa | Significado |
|-----------|---------------|-------------|
| **Membrana sinovial espessada** | Consistência "esponjosa" peri-articular | Sinovite crônica (AR, artrite psoriática) |
| **Derrame articular** | Flutuação, patela dançante (joelho), sinal da balão (tornozelo) | Sinovite aguda, trauma, hemoartrose |
| **Tendão** | Trajeto cordonal firme; crepitação com movimento = tenossinovite | Ruptura parcial = "gap" palpável |
| **Bursa inflamada** | Edema flutuante localizado, quente, superficial | Bursite (olécrano, patelar, subacromial, trocantérica) |
| **Tofos** | Nódulos firmes, brancos/amarelados, subcutâneos | Gota tofácea (urato monossódico) |
| **Linfadenomegalia regional** | Gânglios aumentados próximos à articulação | Artrite séptica, doença sistêmica |
| **Crepitação articular** | Sensação de grânulos ao mobilizar | Degeneração cartilaginosa (artrose) |
| **Espasmo muscular** | Rigidez na palpação, resistência à extensão passiva | Lombalgia muscular, contratura protetora |

