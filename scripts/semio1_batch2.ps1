## 2. Testes Especiais por Região

### Ombro

| Teste | Técnica resumida | Positivo indica |
|-------|-----------------|-----------------|
| **Arco doloroso (Neer)** | Elevação passiva do braço em extensão | Dor entre 70-120° = síndrome do impacto do manguito |
| **Hawkins-Kennedy** | Braço a 90° flexão, força rotação interna | Comprime tendão no espaço subacromial = impacto |
| **Jobe (lata vazia)** | Braço 90° abdução no plano escapular, polegar para baixo, resistência à abdução | Fraqueza = ruptura supraespinal |
| **Speed** | Braço estendido, antebraço supinado, resistência à flexão | Dor no sulco bicipital = tendinite bicipital |
| **Apprehension** | Abduçao + rotação externa passiva | Paciente "trava" por medo = instabilidade anterior do ombro |

### Joelho

