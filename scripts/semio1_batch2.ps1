## Relevância Clínica e Acadêmica

A avaliação da amplitude de movimento (ADM) e dos testes especiais é onde a semiologia encontra a anatomia aplicada. Cada teste especial foi desenvolvido para examinar uma estrutura anatômica específica com sensibilidade e especificidade conhecidas. A capacidade de realizar corretamente o teste de Lachman, o arco doloroso do ombro, o teste de faber e o sinal de Lasègue é o diferencial entre o médico que examina com método e o que "aperta tudo e espera o paciente gritar". Na Uninove, testar conhecimento sobre testes especiais é uma das estratégias favoritas do corpo docente.

---

## 1. Amplitude de Movimento (ADM) — Valores de Referência

| Articulação | Movimento | ADM normal |
|-------------|-----------|------------ |
| **Ombro** | Flexão / Extensão | 180° / 45° |
| | Abdução / Adução | 180° / 45° |
| | Rotação interna / externa | 80° / 90° |
| **Cotovelo** | Flexão / Extensão | 145° / 0° (hiperestensão: até –5°) |
| **Punho** | Flexão / Extensão | 60° / 60° |
| **Quadril** | Flexão / Extensão | 120° / 20° |
| | Abdução / Adução | 45° / 30° |
| **Joelho** | Flexão / Extensão | 135° / 0° |
| **Tornozelo** | Dorsiflexão / Plantiflexão | 20° / 50° |
| **Coluna lombar** | Flexão (Schober) | > 5 cm de expansão marcada 10 cm acima espinhosa S1 |

> **ADM ativa:** paciente realiza o movimento (avalia força + amplitude)
> **ADM passiva:** examinador move a articulação (avalia cápsula + ligamentos; se passiva > ativa → causa muscular)

