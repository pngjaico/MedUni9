## 3. Pontos de Referência por Região

### Joelho:
- **Linha articular medial/lateral:** palpação direta para menisco e ligamentos colaterais
- **Patela:** facetas medial/lateral, tendão patelar abaixo
- **Fossa poplítea:** cisto de Baker (fundo = extensão de derrame sinovial), vasos poplíteos
- **Sinal da tecla patelar (Ballottement):** pressiona a patela — "pula" de volta se houver derrame

### Ombro:
- **Bursa subacromial:** palpação com braço em adução; dor em arco (70-120°) = síndrome impacto
- **Tendão supraespinal:** sua inserção no tubérculo maior (dor em abdução ativa)
- **Articulação acromioclavicular:** compressa direta = artrite AC (comum em atletas)
- **Sulco bicipital (tendão bicipital):** dor à palpação + teste de Speed positivo = tendinite bicipital

### Coluna:
- **Apófises espinhosas:** dor central = fratura, espondilite
- **Paravertebrais:** contração/espasmo = lombalgia muscular
- **Ponto sacroilíaco:** compressão lateral da pelve = artrite sacroilíaca (espondilite)

