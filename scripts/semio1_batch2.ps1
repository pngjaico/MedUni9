# SEMIO1 — Aula 6: Síndromes Musculoesqueléticas Comuns

**Disciplina:** Semiologia I — Sistema Musculoesquelético
**Módulo:** 1 | **Tempo de estudo sugerido:** 12-18 min

---

## Relevância Clínica e Acadêmica

Síndromes musculoesqueléticas como lombalgia, síndrome do impacto do ombro, síndrome do túnel do carpo e fibromialgia são responsáveis por uma fração enorme das consultas na atenção primária e reumatologia. O médico de qualquer especialidade precisa reconhecê-las clinicamente — sem depender de imagem para diagnóstico inicial. A Uninove apresenta essas síndromes em formato de caso clínico com múltipla escolha: você lê a história e precisa identificar a síndrome, justificar pelo exame físico e propor a investigação inicial correta.

---

## 1. Lombalgia

| Tipo | Característica | Duração | Causa |
|------|---------------|---------|-------|
| **Aguda** | < 6 semanas | Mecânica (muscular, postural) | Espasmo muscular, distensão |
| **Subaguda** | 6 sem - 3 meses | Em transição | Misto |
| **Crônica** | > 3 meses | Mecânica ou inflamatória | Artrose facetária, hérnia de disco, espondilite |

**Sinais de alerta ("bandeiras vermelhas") que exigem investigação imediata:**
- Idade > 50 anos com dor nova
- Dor noturna constante (neoplasia, infecção)
- Perda de peso involuntária
- Febre
- Trauma significativo (fratura?)
- Déficit neurológico progressivo
- Incontinência de bexiga/esfíncteres → síndrome da cauda equina (emergência cirúrgica!)

### Hérnia de Disco Lombar — resumo per dermátomo:

| Nível | Motor comprometido | Reflexo | Sensibilidade |
|-------|-------------------|---------|----------------|
| **L4** (comprime L4) | Tibial anterior (dorsiflexão pé fraca) | Patelar reduzido | Face medial da perna |
| **L5** (comprime L5) | Extensor longo hálux (extensão do hálux) | Ausente (L5 sem reflexo confiável) | Dorso do pé, 1° dedo |
| **S1** (comprime S1) | Fibular (eversão), gastrocnêmio (plantiflexão) | Aquileu reduzido | Face lateral do pé |

---

## 2. Síndrome do Impacto do Ombro (Síndrome Subacromial)

**Definição:** compressão do manguito rotador (principalmente supraespinal) e da bursa subacromial no arco subacromial.

**Apresentação:** dor no ombro com abdução ativa entre 70-120° (arco doloroso); piora ao dormir sobre o ombro afetado; fraqueza progressiva com evolução.

**Testes positivos:** Neer (arco doloroso), Hawkins-Kennedy
**Evolução:** tendinite → calcificação → ruptura parcial → ruptura completa, do manguito

**Investigação:** RX ombro (calcificações, redução espaço subacromial); US (ruptura parcial); RNM (ruptura completa)

---

## 3. Síndrome do Túnel do Carpo

**Definição:** compressão do nervo mediano no túnel carpiano (ossos do carpo + retináculo dos flexores).

**Apresentação:** parestesia e dor nos dedos 1-4 (mediano), piora noturna, alivia sacudir a mão ("flick sign"), fraqueza/atrofia do tenar progressiva.

**Testes:** Phalen (hiperflexão 60 seg), Tinel (percussão do carpo)
**Causas:** idiopática (mais comum), gravidez, hipotireoidismo, AR, acromegalia, amiloidose

**Investigação:** eletroneuromiografia (confirma); US (visualiza o nervo comprimido)

---

## 4. Fibromialgia

**Definição:** síndrome de dor crônica difusa, musculoesquelética, sem inflamação objetiva.

**Critérios (ACR 2010):** dor difusa (4 regiões do corpo + axial) por > 3 meses + Widespread Pain Index (WPI) ≥ 7 + Symptom Severity Scale ≥ 5 (ou WPI 3-6 + SSS ≥ 9).

**Associações:** fadiga, distúrbio do sono, cefaleia, síndrome do cólon irritável, dificuldade de concentração ("fibro fog")

**Diagnóstico:** clínico (exames laboratoriais e de imagem NORMAIS — usados para excluir outras causas)

**Tratamento:** atividade física aeróbica (1ª linha), amitriptilina, duloxetina, pregabalina

---

## 5. Artrose (Osteoartrite)

**Definição:** degeneração progressiva da cartilagem articular com formação de osteófitos e remodelação óssea.

**Articulações mais acometidas:** joelhos, quadris, coluna cervical/lombar, mãos (IFD, IFP, trapézio-metacarpal — base do polegar).

**Clínica:** dor mecânica (piora com atividade, melhora com repouso), crepitação, rigidez matinal < 30 min, sem inflamação sistêmica.

**RX:** redução do espaço articular, esclerose subcondral, osteófitos, geodos (cistos subcondrais)

---

## Erros Clássicos em Prova (Uninove)

- **"Fibromialgia = exames alterados":** exames são NORMAIS na fibromialgia. Alterações exigem reavaliação diagnóstica (excluir hipotireoidismo, AR, LES).
- **"Incontinência em lombalgia = apenas sintoma":** incontinência/retenção urinária + dor lombar + déficit neurológico perineal = SÍNDROME DA CAUDA EQUINA = cirurgia de urgência em até 48h.
- **"Síndrome do impacto = ruptura completa do manguito":** impacto é um espectro: tendinite → calcificação → ruptura parcial → completa. No início há apenas dor com arco doloroso.
- **"Hérnia L5-S1 acomete reflexo patelar":** L4 acomete reflexo patelar. Hérnia L5-S1 acomete reflexo AQUILEU (S1) ou ausência de reflexo específico (L5).
- **"Artrose é doença inflamatória":** artrose tem componente inflamatório no líquido sinovial, mas é fundamentalmente DEGENERATIVA. CK, VHS e PCR podem estar levemente elevados, mas nada comparável com AR ou LES.

