| **Gaveta posterior** | Igual à anterior, mas empurrando para trás | Lesão de LCP |
| **McMurray** | Rotação da tíbia + extensão gradual | Estalo doloroso = lesão de menisco (med = rotação int; lat = rotação ext) |
