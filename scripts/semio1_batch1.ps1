## Relevância Clínica e Acadêmica

Doenças musculoesqueléticas são a principal causa de incapacidade funcional e a segunda maior razão de procura por serviços de saúde no Brasil, atrás apenas das doenças respiratórias. Artrite reumatoide, osteoartrite, lombalgia, fibromialgia e fraturas por fragilidade representam enorme carga de sofrimento e perda de produtividade. O médico que sabe examinar o aparelho locomotor com método identifica precocemente erosões articulares, instabilidades ligamentares, radiculopatias e tumores ósseos — antes da imagem, com as próprias mãos. Na Uninove, os fundamentos da semiologia musculoesquelética são a base de todas as aulas seguintes do módulo e cobrados repetidamente em provas de correlação clínica.

