## Relevância Clínica e Acadêmica

A anamnese musculoesquelética é a ferramenta diagnóstica mais poderosa e menos valorizada. Estudos mostram que 70-80% dos diagnósticos em reumatologia e ortopedia são feitos apenas com a história clínica bem conduzida, antes de qualquer exame físico ou laboratorial. A caracterização precisa da dor (qualidade, localização, irradiação, fatores de piora/melhora, duração e padrão temporal) leva diretamente à estrutura comprometida. A Uninove cobra sobretudo a discriminação entre padrões inflamatórios e mecânicos, e a interpretação de casos clínicos a partir de dados da anamnese.

---

## 1. OLDCART — A Sigla da Anamnese da Dor

| Letra | Pergunta | Por que importa |
|-------|----------|-----------------|
| **O** (Onset) | Quando começou? Como começou (súbito/gradual)? | Fratura = súbito; artrose = gradual; gota = hiperaguda noturna |
| **L** (Location) | Onde dói exatamente? Irradia para onde? | Localização + irradiação = estrutura comprometida |
| **D** (Duration) | Há quanto tempo? É contínua ou intermitente? | Aguda < 6 sem; crônica > 3 meses |
| **C** (Character) | Qualidade da dor: queimação, pontada, peso, latejo? | Neuropática = queimação; articular = difusa; óssea = profunda |
| **A** (Aggravating/Alleviating) | O que piora? O que melhora? | Repouso alivia = mecânico; repouso piora = inflamatório |
| **R** (Radiation) | A dor vai para algum lugar? | Dermátomo = radiculopatia; região mal definida = referida |
| **T** (Treatment/Timing) | Já fez algo? Varia com hora do dia? | Rigidez matinal > 1h = inflamatório |

---

## 2. Padrão Inflamatório vs. Mecânico — Diferencial Fundamental

| Característica | Padrão Inflamatório | Padrão Mecânico |
|----------------|--------------------|-----------------| 
| **Rigidez matinal** | > 1 hora (às vezes 2-3h) | < 30 minutos |
| **Repouso** | Piora a dor e a rigidez | Alivia a dor |
| **Atividade física** | Melhora a dor | Piora a dor |
| **Noite** | Piora (dor noturna) | Melhora |
| **Exemplos** | AR, espondilite anquilosante, gota aguda | Artrose, lombalgia mecânica, entorse |

> **Regra de memorização:** Inflamatório = "o motor não aquece" (rigidez matinal longa, melhora com movimento); Mecânico = "quanto mais usa, mais dói" (melhora com repouso).

---

## 3. Perguntas Complementares Essenciais

### Investigação sistêmica:
- **Febre?** → artrite séptica, doença de Lyme, AR sistêmica
- **Perda de peso involuntária?** → neoplasia óssea, artrite paraneoplásica
- **Rash cutâneo?** → lúpus (eritema malar), artrite psoriática (psoríase), dermatomiosite
- **Olhos vermelhos, uveíte?** → espondiloartropatias (HLA-B27 positivo)
- **Infecção recente (trato urinário, diarreía)?** → artrite reativa (síndrome de Reiter)

### Padrão de acometimento articular:
| Padrão | Definição | Sugere |
|--------|----------|--------|
| **Monoartrite** | 1 articulação | Gota, artrite séptica, trauma |
| **Oligoartrite** | 2-4 articulações | Artrite psoriática, artrite reativa |
| **Poliartrite** | ≥ 5 articulações | Artrite reumatoide, LES |
| **Simétrica** | Mesmas articulações bilaterais | Artrite reumatoide |
| **Migratória** | Um local depois outro (não alterna) | Febre reumática, gonocócica |
| **Aditiva** | Novas articulações somam-se sem resolver as anteriores | Artrite reumatoide |

