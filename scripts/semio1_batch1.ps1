## Relevância Clínica e Acadêmica

A inspeção musculoesquelética é o primeiro contato visual com o corpo do paciente — e revela mais do que parece. Deformidades articulares específicas indicam doenças particulares (dedos em fuso = AR, tofos = gota, joelho valgo/varo = artrose em colapso). Atrofia muscular localiza a lesão nervosa. Marcha alterada informa o nível de disfunção funcional. Cicatrizes e deformidades pós-traumáticas contextualizam queixas antigas. Na Uninove, perguntas de inspeção aparecem como "o que você observa no exame" a partir de fotos ou descrições clínicas.

