## 1. Estruturas Avaliadas no Exame Musculoesquelético

| Estrutura | Origem da dor | Achados típicos |
|-----------|--------------|-----------------|
| **Articulação sinovial** | Intra-articular (sinovite, derrame) | Edema, calor, limitação global de movimento |
| **Tendão** | Trajeto ou inserção (tendinite, ruptura) | Dor com movimento ativo resistido |
| **Bursa** | Inflamação da bolsa sinovial | Edema flutuante superficial localizado |
| **Ligamento** | Distensão ou ruptura (trauma) | Dor localizada, instabilidade ao teste |
| **Músculo** | Contração/espasmo/distensão | Dor difusa, piora com esforço |
| **Osso** | Fratura, infecção, tumor | Dor profunda, noturna, independe de posição |
| **Nervo** | Compressão, inflamação (radiculopatia, tunel) | Irradiação, parestesia, déficit motor distal |

