## 3. Tipos de Dor Musculoesquelética

| Tipo | Característica | Exemplo |
|------|---------------|---------|
| **Articular** | Difusa na articulação, piora com todos os movimentos | Artrite (reumatoide, séptica) |
| **Periarticular** | Localizada fora da articulação, piora com movimento específico | Tendinite, bursite |
| **Referida** | Dor sentida longe da origem (víscera → estrutura locomotora) | Dor de ombro direito por patologia biliar; dor sacral por rim |
| **Neuropática** | Irradiação em dermátomo, parestesia, queimação | Ciatalgia (L4-L5-S1), síndrome do túnel do carpo |
| **Óssea** | Profunda, noturna, local fixo | Osteossarcoma, metástase, fratura por estresse |

---

## 4. Termos Semiológicos Essenciais

- **Artralgia:** dor articular SEM sinais inflamatórios (SEM PCDRT: inchaço, calor, rubor)
- **Artrite:** dor articular COM sinais inflamatórios
- **Sinovite:** inflamação da membrana sinovial (causa de artrite)
- **Entesite:** inflamação na inserção tendinosa no osso (sinal de espondiloartrite)
- **Tenossinovite:** inflamação do tendão + sua bainha
- **Crepitação:** sensação de "farelos" à mobilização (degeneração cartilaginosa)
- **Contratura:** encurtamento muscular com resistência à extensão passiva

---

## Erros Clássicos em Prova (Uninove)

- **"Artralgia = artrite":** artralgia é apenas dor articular; artrite requer sinais inflamatórios objetivos (edema, calor, rubor). Essa distinção aparece em toda questão de reumatologia.
- **"Solicitei imagem antes de examinar":** a radiografia só faz sentido com hipótese clínica. Pedir imagem antes do exame físico é erro de método — e erro de questão objetiva.
- **"Dor com todos os movimentos = articular":** só é verdadeiro se a dor é intrarticular. Dor periarticular pode simular limitação global por dor protetora (espasmo muscular).
- **"Testar força muscular antes de avaliar mobilidade":** força isométrica aumenta a pressão articular. Se há suspeita de lesão instável, testar força antes de verificar a amplitude pode ser prejudicial ao paciente.
- **"Entesite é tendinitopatia":** entesite (inserção tendão-osso) é marcadora específica de espondiloartrites (artrite psoriática, espondilite anquilosante). Tendinite é processo diferente, mais localizado no corpo tendinoso.

