- **"Monoartrite aguda = trauma":** monoartrite aguda deve excluir primeiro artrite séptica (emergência!) e gota. Só depois considerar trauma.
- **"Não preciso perguntar sobre peles e olhos na queixa osteoarticular":** doenças como LES, artrite psoriática, síndrome de Reiter e espondilite têm manifestações extra-articulares essenciais para o diagnóstico.
- **"Poliartrite simétrica = sempre artrite reumatoide":** LES também causa poliartrite simétrica, além de serosite, nefrite e rash. A história sistêmica distingue.

