## Erros Clássicos em Prova (Uninove)

- **"Nó de Heberden = artrite reumatoide":** Nó de Heberden (IFD) e Bouchard (IFP) são sinais de ARTROSE, não de AR. AR poupa IFD — acomete MCF e IFP.
- **"Desvio ulnar = artrose":** desvio ulnar dos dedos é sinal de artrite REUMATOIDE avançada, não de artrose (artrose gera osteófitos, não desvio ulnar).
- **"Marcha de Trendelenburg = fraqueza do glúteo máximo":** Trendelenburg = fraqueza do GLÚTEO MÉDIO (abdutor da pelve). Glúteo máximo é extensor do quadril.
- **"Escoliose = desvio da coluna sempre estrutural":** escoliose postural (funcional) ocorre por proteção à dor (espasmo muscular, escoliose antálgica); desaparece na flexão anterior. Escoliose estrutural (real) mantém a gibosidade no teste de Adams.
- **"Tofo = tumor":** tofo é depósito de urato monossódico em tecidos moles — sinal de GOTA crônica. Aparência brancacenta, firme, subcutânea, típico em orelha, cotovelo e dedos.

