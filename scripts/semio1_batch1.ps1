## 3. Inspeção de Regiões Específicas

### Mãos e punhos (riqueza semiológica):
- Eritema palmar → cirrose hepática, AR
- Pápulas de Gottron (cotovelos) → dermatomiosite
- Fenômeno de Raynaud (branqueamento → cianose → rubor) → esclerodermia, LES, ocupacional

### Ombro:
- Atrofia do trapézio/deltóide → lesão de nervo espinal (XI) ou axilar
- Posição em rotação interna do ombro com braço pendurado → luxação anterior crônica

### Coluna:
- Sinal de Schober (< 5 cm de expansão em flexão) → limitação lombar (fibrose em espondilite)
- Gibosidade torácica → escoliose estrutural

