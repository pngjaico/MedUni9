### Tipos de marcha anormal:

| Tipo | Aparência | Causa neurológica ou ortopédica |
|------|-----------|----------------------------------|
| **Trendelenburg** | Pelve cai para o lado oposto ao apoio | Fraqueza do glúteo médio (lesão L5, displasia do quadril) |
