## 2. A Hierarquia do Exame — Sequência Obrigatória

A ordem do exame não é aleatória — cada etapa influi na interpretação da seguinte:

1. **Anamnese** → define hipótese → orienta o exame
2. **Inspeção** (sem tocar) → assimetria, deformidade, edema, atrofia
3. **Palpação** → pontos dolorosos, temperatura, crepitação
4. **Amplitude de movimento** → ativa (paciente move) e passiva (examinador move)
5. **Força muscular** → escala MRC (0-5)
6. **Testes especiais** → confirmam/excluem lesões específicas
7. **Exame vascular e neurológico** → pulsos, sensibilidade, reflexos

> **Regra de ouro:** nunca palpar antes de inspecionar; nunca testar força antes de avaliar mobilidade. A inversão da sequência "cria" achados artificiais.

