## 1. Características Gerais do Tecido Cartilaginoso

- **Avascular:** depende de difusão da pericôndrio
- **Sem nervação:** explica por que artrose avançada pode demorar a doer (sem nervos na cartilagem; a dor vem do osso subcondral exposto)
- **Sem vasos linfáticos**
- Célula: **condrócito** (alojado em lacunas)
- MEC: rica em colágeno + proteoglicanas + GAGs (condroitim e queratam sulfato)
- Alta capacidade de **absorção de água**: conferida pelas GAGs — respondem por ~70-80% do peso da cartilagem

