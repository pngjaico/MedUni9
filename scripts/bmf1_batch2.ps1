## Ponte com a Clínica

Hérnia de disco intervertebral: o anel fibroso (fibrocartilagem) rompe-se e permite que o núcleo pulposo (rico em GAGs e água) hernie para o canal vertebral, comprimindo a raiz nervosa. Na lombalgia com irradiação para o membro inferior, o raciocínio diagnóstico começa pela histologia — fibrocartilagem + pressão + raiz nervosa. A degeneração do disco leva à perda de agrecano, consequente perda de água e, portanto, perda de altura como estrutura amortecedora. Isso explica por que adultos mais velhos "perderam altura" — não apenas por osteoporose, mas também pela degeneração dos discos.

