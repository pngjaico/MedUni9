## Erros Clássicos em Prova (Uninove)

- **Cartilagem articular tem pericôndrio:** a cartilagem hialina articular e a placa epifisária são exceções — não possuem pericôndrio.
- **Fibrocartilagem tem colágeno tipo II:** fibrocartilagem usa colágeno tipo I (feixes grossos e visíveis); hialina e elástica usam tipo II.
- **Cartilagem hialina = fibrocartilagem:** hialina tem MEC homogênea (fibras não visíveis na HE); fibrocartilagem tem feixes de colágeno I visíveis e não tem pericôndrio.
- **Condrócito = condroblasto:** condroblasto produz a MEC (ativo); condrócito é o aprisionado na lacuna (mantém a MEC com atividade reduzida).
- **Cartilagem elástica na traqueia:** a traqueia tem cartilagem hialina (anéis em ferradura); a cartilagem elástica está na orelha externa, epiglote.

