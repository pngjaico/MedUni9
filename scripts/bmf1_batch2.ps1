## Relevância Clínica e Acadêmica

O tecido ósseo é um tecido conjuntivo especializado em constante remodelação — não é estático. O equilíbrio entre osteoblastos (constroem) e osteoclastos (reabsorvem) determina a densidade óssea ao longo da vida. Quando esse equilíbrio se rompe — pela menopausa, pelo hiperparatireoidismo, pela imobilização — surge a osteoporose. A Uninove cobra ossificação endocondral (que ocorre em ossos longos) e intramembranosa (crânio, clavícula) porque elas são base para entender fraturas e crescimento ósseo.

---

## 1. Células do Tecido Ósseo

| Célula | Origem | Função | Marcador |
|--------|--------|--------|----------|
| **Osteoblasto** | Mesenquimal | Síntese de MEC óssea (osteoide) e mineralização | Fosfatase alcalina ↑ |
| **Osteócito** | Osteoblasto aprisionado | Mecanossensão; mantém MEC mineralizada | Lacunas ósseas |
| **Osteoclasto** | Monócito/macrófago | Reabsorção óssea (secreta H⁺ + catepsinas) | TRAP ↑ |
| **Célula osteoprogenitora** | Mesenquimal indiferenciada | Precursora dos osteoblastos; no periósteo | — |

> **Detalhe clínico:** na osteoporose, o osteoclasto "vence" o osteoblasto. O **PTH** (hormônio paratireóideo) estimula osteoclastos (cálcio no sangue ↑); a **calcitonina** inibe osteoclastos (cálcio no sangue ↓).

---

## 2. MEC Óssea

| Componente | Proporção | Função |
|------------|-----------|--------|
| **Orgânico** (osteoide) | ~35% | Colágeno tipo I (flexibilidade) + osteocalcina |
| **Inorgânico** (mineral) | ~65% | Hidroxiapatita — Ca₁₀(PO₄)₆(OH)₂ (rigidez) |

A combinação de colágeno + hidroxiapatita dá ao osso **rigidez** (mineral) + **flexibilidade** (colágeno), tornando-o altamente resistente. Osso sem mineral = mole (raquitismo); osso sem colágeno = quebradiço (osteogênese imperfeita).

---

## 3. Organização Microscópica — Ósteon (Sistema de Havers)

O **ósteon** é a unidade estrutural do osso compacto:

- **Canal de Havers** (central): contém vasos e nervos
- **Lamelas** concêntricas: camadas de MEC mineralizada ao redor do canal
- **Lacunas:** espaços ocupados pelos osteócitos
- **Canalículos:** canais que conectam lacunas entre si e ao canal de Havers (difusão de nutrientes)
- **Canal de Volkmann:** conecta canais de Havers horizontalmente; perpendicular ao eixo ósseo

---

## 4. Ossificação Intramembranosa

Ocorre diretamente no **tecido conjuntivo mesenquimal** — sem molde cartilaginoso.

| Onde ocorre | Ossos formados |
|-------------|----------------|
| Derme do crânio | Parietal, frontal, occipital |
| Mandíbula, maxila | Ossos da face |
| Clavícula (parte) | Parte medial da clavícula |

**Processo:** células mesenquimais → osteoblastos → secretam osteoide → mineralização → espículas ósseas → fusão → tábua óssea. A fontanela do recém-nascido é onde a ossificação intramembranosa ainda não está completa.

---

## 5. Ossificação Endocondral

Ocorre sobre um **modelo cartilaginoso hialino** que é progressivamente substituído por osso. É o processo da maioria dos ossos do esqueleto (longos, curtos, irregulares).

**Etapas simplificadas (osso longo):**
1. Condrócitos no centro da diáfise hipertrofiam e morrem
2. Vasos invadem → núcleo de ossificação primário (diáfise)
3. Na epífise: núcleo de ossificação secundário
4. Entre diáfise e epífise fica a **placa epifisária** (cartilagem de crescimento)
5. Com a puberdade (ação dos hormônios sexuais): fusão da placa → crescimento encerra

| Tipo | Molde | Exemplos |
|------|-------|---------|
| Intramembranosa | Tecido conjuntivo | Crânio, clavícula (parte) |
| Endocondral | Cartilagem hialina | Fêmur, tíbia, vértebras, costelas |

---

## 6. Remodelação Óssea

O osso adulto se renova constantemente (~10% ao ano). A **remodelação** ocorre em unidades chamadas BMU (Bone Multicellular Unit):

Osteoclasto reabsorve → lacuna de reabsorção → osteoblastos preenchem com osteoide → mineralização.

**Regulação:**
- **PTH** → ativa osteoclastos → ↑ Ca²⁺ sérico
- **Calcitonina** → inibe osteoclastos → ↓ Ca²⁺ sérico  
- **1,25(OH)₂D₃ (vitamina D ativa)** → ↑ absorção intestinal de Ca e P → mineralização
- **Estrogênio** → inibe osteoclastos → protege a massa óssea (à menopausa ↓ estrogênio → osteoporose)

