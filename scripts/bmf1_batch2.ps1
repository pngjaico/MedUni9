## 3. Condrócito e MEC

O **condrócito** é a única célula da cartilagem madura. Deriva do **condroblasto**, que produz a MEC e depois fica aprisionado em suas próprias lacunas, transformando-se em condrócito.

A MEC cartilaginosa contém:
- **Colágeno** (tipo II na hialina/elástica; tipo I na fibrocartilagem)
- **Agrecano** (maior proteoglicana da cartilagem): cadeia de condroitim sulfato + queratam sulfato ancoradas em ácido hialurônico → retém água → suporta compressão
- **Água** (~70% do peso úmido)

---

## 4. Regeneração da Cartilagem

A regeneração é **muito limitada** porque:
1. Avascular → sem chegada de células de reparo via sangue
2. Sem células-tronco abundantes localmente
3. Poucas células (condrócitos têm proliferação muito limitada)

Estratégias clínicas: transplante de condrócitos autólogos (ACI), implante de matriz extracelular, próteses articulares.

