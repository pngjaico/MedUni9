- **Osteoclasto origina do mesoderma:** errado — osteoclasto origina da linhagem monócito/macrófago (hematopoética).
- **Ossificação endocondral = para todos os ossos:** crânio e parte da clavícula são intramembranosos — sem molde cartilaginoso.
