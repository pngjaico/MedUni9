## Relevância Clínica e Acadêmica

As articulações são o componente do aparelho locomotor mais frequentemente envolvido em patologias — artrite, artrose, entorse, luxação. Para interpretar corretamente um quadro articular, você precisa saber a classificação da articulação, quais estruturas ela possui (cápsula, membrana sinovial, meniscos) e quais movimentos são possíveis. A Uninove cobra com frequência a diferença entre articulações sinoviais e não-sinoviais, além das subclassificações das sinoviais (gínglimo, elipsoide, esferartrosis, etc.).

---

## 1. Classificação das Articulações — Funcional

| Tipo funcional | Mobilidade | Exemplo |
|----------------|------------|---------|
| **Sinartrose** | Imóvel | Suturas do crânio |
| **Anfartrose** | Levemente móvel | Sínfise púbica, discos intervertebrais |
| **Diartrose** | Amplamente móvel | Joelho, ombro, cotovelo |

---

## 2. Classificação Estrutural

### Articulações Fibrosas (Sinartroses)

| Subtipo | Descrição | Exemplo |
|---------|-----------|---------|
| **Sutura** | Ossos unidos por tecido fibroso denso; sem mobilidade | Sutura coronal, lambdóide, sagital |
| **Sindesmose** | Membrana interóssea ou ligamento; algum movimento | Sindesmose tibiofibular distal |
| **Gonfose** | Dente implantado em alvéolo por ligamento periodontal | Dente no osso alveolar |

### Articulações Cartilagíneas (Anfiartoses)

| Subtipo | Cartilagem | Exemplo |
|---------|------------|---------|
| **Sincondrose** | Cartilagem hialina; temporária (funde na puberdade) | Placa epifisária, articulação costoesternal (1ªcostela) |
| **Sínfise** | Fibrocartilagem; permanente | Sínfise púbica, discos intervertebrais |

### Articulações Sinoviais (Diartroses)

Todas as articulações sinoviais possuem:
- **Superfícies articulares** cobertas por cartilagem hialina
- **Cápsula articular** com camada fibrosa (externa) + membrana sinovial (interna)
- **Líquido sinovial** — produzido pela membrana sinovial; lubrifica e nutre a cartilagem
- **Ligamentos** (reforçam a cápsula)

---

## 3. Tipos de Articulações Sinoviais por Forma

| Tipo | Movimentos | Exemplo |
|------|-----------|---------|
| **Plana (deslizamento)** | Deslizamento | Articulações intercarpianas, intercuneifor |
| **Gínglimo (dobradiça)** | Flexão/extensão apenas (1 eixo) | Cotovelo (úmero-ulnar), interfalangeanas |
| **Trocoide (pivô)** | Rotação apenas (1 eixo) | Atlantoaxial (C1-C2), rádio-ulnar proximal |
| **Condilartrose (elipsoide)** | Flexão+extensão+abd+add (2 eixos) | Radiocarpal (punho), metacarpofalangeana |
| **Sellar (em sela)** | Flexão+extensão+abd+add (2 eixos, mais amplitude) | Trapézio-metacarpal (base do polegar) |
| **Esferartrosis (enartrosis)** | Multiaxial — todos os movimentos | Glenoumeral (ombro), coxofemoral (quadril) |

---

## 4. Estruturas Especiais das Articulações Sinoviais

| Estrutura | Função | Onde |
|-----------|--------|-------|
| **Meniscos** | Congruência articular + amortecimento + distribuição de carga | Joelho (medial e lateral) |
| **Lábio articular** | Aprofunda a cavidade glenóide/acetabular | Ombro (lábio glenoide), quadril (lábio acetabular) |
| **Discos articulares** | Separa a cavidade em 2 compartimentos | ATM (temporomandibular), esternoclavicular |
| **Bursas** | Saco com líquido sinovial; reduz fricção entre tendão e osso | Patela, acrômio, olécrano |

---

## Erros Clássicos em Prova (Uninove)

- **Sinartrose = sinusoidal ou sínfise:** sutura é sinartrose (imóvel); sínfise é anfartrose (fibrocartilagem, levemente móvel).
- **Cotovelo é esferartrosis:** o cotovelo (úmero-ulnar) é gínglimo — flexão/extensão apenas. A articulação do ombro é esferartrosis.
- **Cartilagem articular é nutrida por vasos:** a cartilagem hialina que reveste as superfícies articulares é avascular — nutrida por difusão do líquido sinovial e do osso subcondral.
- **Menisco é parte do fêmur:** meniscos são estruturas de fibrocartilagem interpostas entre fêmur e tíbia — não são parte do osso.
- **A sincondrose é permanente:** sincondrose (cartilagem hialina) é temporária — funde-se com a maturidade. Sínfise (fibrocartilagem) é permanente.

