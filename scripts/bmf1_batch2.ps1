# BMF1 — Aula 5: Tecido Ósseo — Estrutura e Ossificação

**Disciplina:** Bases Morfofuncionais 1 — Locomotor e Digestório
**Módulo:** 1 | **Tempo de estudo sugerido:** 10-15 min

