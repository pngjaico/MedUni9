## Relevância Clínica e Acadêmica

O esqueleto é mais do que suporte — é reservatório mineral, fábrica de células sanguíneas e proteção de órgãos vitais. As classificações dos ossos por forma e estrutura são cobradas diretamente nas provas e fundamentam a compreensão das fraturas (por que a diáfise de um osso longo fratura diferente do corpo de uma vértebra). A Uninove gosta de questões que ligam tipo ósseo a função clínica ou a tipo de fratura frequente.

---

## 1. Funções do Esqueleto

| Função | Exemplo clínico |
|--------|-----------------|
| **Suporte mecânico** | Sustentação do corpo, postura |
| **Proteção de órgãos** | Crânio (encéfalo), caixa torácica (coração/pulmões), bacia (vísceras pélvicas) |
| **Locomoção** | Alavancas para músculos se inserirem |
| **Hematopoese** | Medula óssea vermelha produz células sanguíneas |
| **Reservatório mineral** | 99% do Ca²⁺ corporal nos ossos; mobilizável sob ação do PTH |
| **Armazenamento de gordura** | Medula óssea amarela em adultos |

---

## 2. Divisões do Esqueleto

| Divisão | Ossos | Quantidade |
|---------|-------|-----------|
| **Axial** | Crânio, coluna, costelas, esterno | ~80 ossos |
| **Apendicular** | Membros superiores e inferiores + cinturas | ~126 ossos |
| Total no adulto | — | ~206 ossos |

> Recém-nascido tem ~270 ossos — muitos se fundem ao longo do desenvolvimento.

---

## 3. Classificação dos Ossos por Forma

| Tipo | Características | Exemplos |
|------|-----------------|---------|
| **Longo** | Diáfise + epífises; comprimento > largura | Fêmur, úmero, tibia, rádio |
| **Curto** | Dimensões aproximadamente iguais | Carpo (escafoide, lunato), tarso (calcâneo) |
| **Plano (chato)** | Lâminas de osso compacto com díploe | Parietal, escápula, esterno, ilíaco |
| **Irregular** | Forma complexa, não se encaixa nas outras | Vértebras, maxilar, etmoide |
| **Sesamoide** | Dentro de tendões; amortece pressão | Patela (o maior), sesamoides do hallux |
| **Pneumático** | Contém cavidades preenchidas por ar | Frontal, maxilar, etmoide, esfenoide |

---

## 4. Estrutura Macroscópica de um Osso Longo

| Porção | Descrição |
|--------|-----------|
| **Epífise** | Extremidades do osso longo; osso esponjoso coberto por placa de cartilagem |
| **Metáfise** | Região de transição; local da **cartilagem de crescimento (epifisária)** |
| **Diáfise** | Corpo tubular; osso compacto com canal medular |
| **Periósteo** | Membrana fibrosa que cobre a diáfise; rica em osteoprogenitoras e vasos |
| **Endósteo** | Revestimento interno do canal medular |
| **Medula óssea vermelha** | Epífises + ossos esponjosos; hematopoese ativa |
| **Medula óssea amarela** | Diáfise de adultos; substituição por gordura com a idade |

> A **cartilagem epifisária** (placa de crescimento) fecha na puberdade. Em crianças, fraturas na metáfise podem comprometer o crescimento.

---

## 5. Osso Compacto vs. Osso Esponjoso

| Característica | Osso Compacto | Osso Esponjoso (Trabecular) |
|-----------------|--------------|------------------------------|
| Organização | Osteons (sistemas de Havers) | Trabéculas com espaços medulares |
| Localização | Diáfise, superfícies | Epífises, vértebras, ossos planos |
| Função | Resistência mecânica | Absorção de impacto, hematopoese |
| Porosidade | Baixa (5-10%) | Alta (50-90%) |
| Impacto clínico | Fraturas de diáfise (traçado transversal ou espiroide) | Fraturas por compressão (vértebras em osteoporose) |

