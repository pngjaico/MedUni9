## 3. Fibroblasto — A Célula Central do Conjuntivo

O **fibroblasto** é a célula que mantém a MEC e protagoniza a cicatrização:

1. **Fibroblasto ativo (fibroblasto):** sintetiza colágeno, elastina, GAGs; núcleo grande e oval; REG abundante
2. **Fibroblasto inativo (fibrócito):** célula em repouso; núcleo alongado, pequeno; pouca atividade sintética

Na cicatrização:
- Fase inflamatória (0-4 dias): limpeza por macrófagos
- Fase proliferativa (4-21 dias): fibroblastos migram, sintetizam colágeno III (reticular), formam tecido de granulação
- Fase de remodelação (21 dias – 2 anos): colágeno III substituído por colágeno I; miofibroblastos contraem a ferida

---

## 4. Mastócito e Alergia — Conexão com a Clínica

O **mastócito** contém grânulos de **histamina**, **heparina** e outros mediadores. Quando **IgE** (produzida por plasmócitos em resposta a alérgeno) se liga ao receptor FcεRI do mastócito e há re-exposição ao alérgeno → **degranulação** → liberação maciça de histamina → vasodilatação + contração de músculo liso + aumento de permeabilidade vascular.

Na anafilaxia: esse processo é sistêmico, causando urticária, broncospasmo, hipotensão. O tratamento de emergência é **adrenalina** (epinefrina), que reverte vasodilatação e broncoconstrição.

