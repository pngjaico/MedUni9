### O que você PRECISA saber

- **MEC:** fibras (colágeno, elástica, reticular) + substância fundamental (GAGs + proteoglicanas)
- **Colágeno:** tipo I = tendão; tipo II = cartilagem hialina; tipo III = reticular; tipo IV = membrana basal
- **Fibroblasto ativo:** sintetiza MEC; **fibrócito:** inativo, em repouso
- **Mastócito:** grânulos de histamina; degranulação por IgE → hipersensibilidade tipo I
- **Macrófago:** fagocitose + apresentação de antígeno; derivado do monócito
- **Plasmócito:** derivado do linfócito B; produz anticorpos (Ig)
- **Cicatrização:** inflamação → proliferação (fibroblasto + col. III) → remodelação (col. I)

