## Erros Clássicos em Prova (Uninove)

- **Patela é osso longo:** patela é osso sesamoide — o maior do corpo, localizado no tendão do quadríceps.
- **Medula óssea amarela realiza hematopoese:** em adultos, a amarela é predominantemente gordurosa; hematopoese ocorre na vermelha (epífises e ossos planos).
- **Esqueleto axial inclui os membros:** membros pertencem ao esqueleto apendicular; axial = cabeça + tronco.
- **A criança tem 206 ossos:** adultos têm ~206; recém-nascidos têm ~270 (muitos ainda não fundidos).
- **Fratura na "diáfise femoral" pode ser em qualquer osso:** diáfise é exclusiva dos ossos longos — ossos curtos, planos e irregulares não têm diáfise.

