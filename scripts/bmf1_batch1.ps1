## Relevância Clínica e Acadêmica

O tecido conjuntivo está em todo lugar — é o "cimento" do corpo. Quando ele falha (doenças do colágeno, inflamação crônica, fibrose), as consequências são sistêmicas. A Uninove cobra células e MEC do conjuntivo porque esse conhecimento se conecta diretamente com imunologia (papel do mastócito/macrófago), farmacologia (anti-inflamatórios agem aqui) e patologia (fibrose, inflamação granulomatosa). Conhecer o fibroblasto e o colágeno é pré-requisito para entender cicatrização de feridas, algo que todo médico usa diariamente.

---

## 1. Componentes da MEC (Matriz Extracelular)

A MEC é produzida pelos **fibroblastos** e composta por:

### Fibras

| Fibra | Proteína | Características | Localização |
|-------|----------|-----------------|-------------|
| **Colágeno** | Colágeno (tipos I, II, III, IV...) | Resistência à tração; mais abundante do corpo | Tendões (tipo I), cartilagem (tipo II), MBs (tipo IV) |
| **Elástica** | Elastina + fibrilina | Retorna ao comprimento original após deformação | Aorta, pele, ligamento amarelo |
| **Reticular** | Colágeno III | Fibras finas, formam redes de sustentação | Linfonodos, baço, fígado (estroma) |

### Substância fundamental

Composta por **glicosaminoglicanas (GAGs)** — ácido hialurônico, condroitim sulfato, heparam sulfato — e **proteoglicanas**. Formam um gel hidratado que age como lubrificante e filtro molecular.

