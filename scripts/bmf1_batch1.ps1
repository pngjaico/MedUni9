## Erros Clássicos em Prova (Uninove)

- **Fibrócito é o mesmo que fibroblasto:** fibrócito é o fibroblasto inativo (inativo = "cito"). Fibroblasto ativo é quem sintetiza colágeno.
- **Mastócito libera histamina sem IgE:** a degranulação do mastócito via IgE é o mecanismo da hipersensibilidade Tipo I. Sem IgE não há esse mecanismo (via complemento é diferente).
- **Colágeno tipo II está em tendões:** tendão usa colágeno tipo I (resistência à tração); cartilagem hialina usa tipo II.
- **Macrófago = macrófago fixo (histiócito) = monócito:** são a mesma linhagem celular em locais diferentes — monócito no sangue, macrófago no tecido, histiócito = macrófago fixo do conjuntivo.
- **Plasmócito produz histamina:** plasmócito produz anticorpos (Ig) — histamina é do mastócito.

