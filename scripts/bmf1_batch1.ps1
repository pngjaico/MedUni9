## Relevância Clínica e Acadêmica

Os quatro tecidos básicos são a base de toda a patologia — sem entender estrutura e função normais, você não consegue reconhecer o que está errado no tecido alterado. As perguntas de histologia na Uninove frequentemente apresentam uma imagem microscópica e pedem identificação do tecido ou do tipo celular. Mais do que memorizar, você precisa entender a lógica de cada tecido: por que o epitelial é avascular? Por que o muscular cardíaco é involuntário com estriação? Por que o nervoso não se regenera bem?

---

## 1. Origem dos Tecidos — Camadas Germinativas

Os quatro tecidos derivam das três camadas do embrião:

| Tecido | Camada germinativa |
|--------|-------------------|
| Epitelial | Ectoderma, mesoderma ou endoderma (depende do local) |
| Conjuntivo | Mesoderma |
| Muscular | Mesoderma |
| Nervoso | Ectoderma (neuroectoderma) |

---

## 2. Tecido Epitelial

Células **muito justapostas**, com **pouca ou nenhuma MEC** entre elas. **Avascular** — recebe nutrição por difusão a partir do conjuntivo subjacente.

| Subtipo | Função | Localização |
|---------|--------|-------------|
| **Revestimento** | Cobrir superfícies e cavidades | Pele, mucosas, vasos |
| **Glandular** | Produzir e secretar substâncias | Glândulas salivares, fígado, pâncreas |

Características marcantes:
- Células **polarizadas** (face apical diferente da basal)
- Assenta sobre **membrana basal**
- Alta capacidade de **renovação celular** (vilosidades intestinais renovam a cada 3-5 dias)
- **Avascular** — sem vasos dentro do epitélio

---

## 3. Tecido Conjuntivo

O mais **abundante** e **variado**. Células **esparsas** em matriz extracelular rica (fibras + substância fundamental). Tem **vascularização própria**.

Funções: suporte, conexão, defesa, nutrição.

| Tipo | Fibras | Localização |
|------|--------|-------------|
| Frouxo | Poucas, desorganizadas | Derme papilar, lâmina própria |
| Denso modelado | Paralelas | Tendões, ligamentos |
| Denso não modelado | Entrelaçadas | Derme reticular |
| Adiposo | Adipócitos predominam | Hipoderme, omento |
| Reticular | Fibras reticulares finas | Linfonodos, baço |
| Elástico | Fibras elásticas | Ligamento amarelo, aorta |

Células do conjuntivo: **fibroblasto** (produz MEC), **mastócito** (libera histamina), **macrófago** (fagocitose), **plasmócito** (produz Ig), **adipócito** (armazena lipídios).

---

## 4. Tecido Muscular

Especializado em **contração** por actina e miosina. Três tipos com diferenças cruciais:

| Característica | Esquelético | Cardíaco | Liso |
|----------------|-------------|----------|------|
| Estriação | Sim | **Sim** | Não |
| Controle | Voluntário | **Involuntário** | Involuntário |
| Núcleos | Múltiplos, periféricos | 1-2, centrais | 1, central |
| Discos intercalares | Não | **Sim** | Não |
| Regeneração | Limitada (células satélite) | Muito limitada | Boa |
| Local | Músculos do corpo | Coração | Vísceras, vasos |

> **Pegadinha clássica:** cardíaco tem estriação (como esquelético) mas é involuntário (como liso).

---

## 5. Tecido Nervoso

Células: **neurônios** (condução do impulso) + **células gliais** (suporte, mielinização, defesa).

**Neurônio:** pericário (corpo celular) + dendritos (recebem) + axônio (enviam impulso).

| Glia | Sistema | Função |
|------|---------|--------|
| **Astrócito** | SNC | Suporte, barreira hematoencefálica |
| **Oligodendrócito** | SNC | Mielinização |
| **Célula de Schwann** | SNP | Mielinização |
| **Microglia** | SNC | Defesa imunológica |
| **Célula ependimária** | SNC | Reveste ventrículos, produz LCR |

**Regeneração nervosa:** axônio do SNP pode se regenerar (Schwann guia). SNC regenera mal (sem guia eficiente).

---

## Erros Clássicos em Prova (Uninove)

- **Tecido epitelial é vascularizado:** é avascular — depende de difusão do conjuntivo.
- **Músculo cardíaco é voluntário:** é involuntário, apesar de ter estriação.
- **Oligodendrócito mieliniza no SNP:** no SNP quem mieliniza é a Célula de Schwann; oligodendrócito é SNC.
- **Músculo liso tem estriação:** não tem — a ausência de estriação é justamente o que o define como "liso".
- **Núcleo do músculo esquelético é central:** é periférico (ao contrário do cardíaco, que tem 1-2 centrais).

