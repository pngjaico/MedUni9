## Erros Clássicos em Prova (Uninove)

- **Posição anatômica com palma para dentro:** a palma na posição anatômica está para frente (supinação) — não para dentro. Isso muda os referenciais anterior/posterior na mão.
- **Confundir plano frontal com plano sagital:** frontal (coronal) divide em frente e trás; sagital divide em esquerda e direita. A TC de tórax "axial" é transversal.
- **Chamar de "lado esquerdo do joelho":** em anatomia, usa-se medial/lateral referenciado à linha média — não "esquerdo/direito" para descrever estruturas internas.
- **Abdução = aproximar:** abdução AFASTA da linha média; adução APROXIMA. ("ABdução = ABrir").
- **Pronação = palma para cima:** pronação é palma para baixo/trás (rádio cruza ulna). Supinação = palma para cima.

