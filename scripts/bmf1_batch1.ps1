## Ponte com a Clínica

Uma cicatriz queloide é o resultado de um fibroblasto que não recebe o sinal de parar — continua sintetizando colágeno I além da área da ferida. No lúpus eritematoso sistêmico, há deposição de imunocomplexos na MEC de múltiplos órgãos (articulações, rins, pele). Na síndrome de Marfan, uma mutação no gene da fibrilina (proteína das fibras elásticas) causa fragilidade da aorta e lente ocular — porque elasticidade é a propriedade que está comprometida.

