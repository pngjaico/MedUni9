## Relevância Clínica e Acadêmica

A anatomia humana é a linguagem universal da medicina. Sem dominar a posição anatômica e os termos de posição, direção e planos, você não consegue descrever um achado clínico, ler um exame de imagem, redigir um prontuário ou dialogar com qualquer especialista. O erro de se referir a uma lesão como "no lado esquerdo do joelho" sem referenciar plano ou direção anatômica pode custar uma cirurgia errada. A Uninove cobra esse tema em quase toda prova de módulo 1 como base para questões de anatomia aplicada.

---

## 1. Posição Anatômica

A **posição anatômica** é o padrão universal de referência para toda descrição em anatomia:

> Indivíduo de pé, ereto, olhando para frente, membros superiores ao lado do corpo com **palmas voltadas para frente** (supinação), pés paralelos.

**O detalhe que mais cai:** a palma está para frente — não para dentro. Isso altera todos os referenciais anteriores/posteriores no membro superior.

---

## 2. Termos de Posição e Direção

| Termo | Significado | Oposto |
|-------|-------------|--------|
| **Superior** (cranial) | Em direção à cabeça | Inferior (caudal) |
| **Anterior** (ventral) | Em direção à frente do corpo | Posterior (dorsal) |
| **Medial** | Mais próximo da linha média | Lateral |
| **Proximal** | Mais próximo da raiz do membro | Distal |
| **Superficial** | Mais próximo da pele | Profundo |
| **Ipsilateral** | Mesmo lado do corpo | Contralateral |

Termos regionais específicos: **palmar** = anterior da mão; **plantar** = inferior do pé; **dorsal** na mão = posterior.

---

## 3. Planos de Secção

| Plano | Divide o corpo em | Exemplo de uso |
|-------|-------------------|----------------|
| **Sagital mediano** | Metades direita e esquerda iguais | Linha média do crânio |
| **Sagital paramediano** | Direita e esquerda desiguais | Qualquer plano paralelo ao mediano |
| **Frontal (coronal)** | Anterior e posterior | TC de coluna (sagital no texto, coronal na imagem) |
| **Transversal (axial ou horizontal)** | Superior e inferior | Tomografia de abdome — "corte axial" |

**Regra rápida:** Sagital → D/E | Frontal → frente/trás | Transversal → cima/baixo

---

## 4. Eixos de Movimento

| Eixo | Direção | Movimentos |
|------|---------|------------|
| **Longitudinal** (vertical) | Cabeça → pés | Rotação medial e lateral |
| **Transversal** | Direita → esquerda | Flexão e extensão |
| **Ântero-posterior** | Frente → trás | Abdução e adução |

---

## 5. Movimentos Fundamentais

| Movimento | Definição |
|-----------|-----------|
| **Flexão** | Diminui o ângulo articular |
| **Extensão** | Aumenta o ângulo articular |
| **Abdução** | Afasta da linha média do corpo |
| **Adução** | Aproxima da linha média do corpo |
| **Rotação medial** | Gira em direção à linha média |
| **Rotação lateral** | Gira para fora da linha média |
| **Pronação** | Rádio cruza a ulna; palma para baixo/trás |
| **Supinação** | Rádio paralelo à ulna; palma para cima/frente |
| **Inversão** | Planta do pé para medial |
| **Eversão** | Planta do pé para lateral |
| **Circundução** | Combinação de flex+ext+abd+add em cone |

