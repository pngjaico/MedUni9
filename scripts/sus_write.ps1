## Relevância Clínica e Acadêmica

Entender por que as pessoas adoecem é o ponto de partida de toda a medicina. Não basta saber diagnosticar e tratar — o médico que ignora os determinantes da doença vai repetir, ao longo da carreira, os mesmos fracassos terapêuticos em pacientes que voltam mais doentes porque o contexto de vida deles nunca mudou. A Uninove cobra esse assunto em provas teóricas de SUS e nas apostilas de semiologia justamente porque o raciocínio clínico ampliado — que enxerga o paciente no território, na família, na renda e na escolaridade — é o que diferencia um médico de APS competente.

Este tema conecta diretamente com as aulas seguintes de organização do SUS, pois toda a estrutura de Atenção Básica (ESF, NASF, PNAB) foi desenhada para agir sobre determinantes sociais, não apenas sobre doenças já instaladas.

