## 1. Definição e Contextualização

**Saúde**, segundo a OMS (1948), é "estado de completo bem-estar físico, mental e social, e não apenas ausência de doença". Na prática, essa definição é criticada por ser utópica — bem-estar completo nunca é atingido. A definição operacional mais usada hoje é a de **Sérgio Arouca**: saúde é resultado das condições de alimentação, habitação, educação, renda, meio ambiente, trabalho, transporte, emprego, lazer e acesso a serviços de saúde.

O **processo saúde-doença** é dinâmico: não é um estado fixo, mas uma resultante contínua entre fatores protetores e agravantes que atuam sobre o indivíduo e a coletividade.

| Modelo | Concepção | Limitação |
|--------|-----------|-----------|
| Mágico-religioso | Doença como punição divina | Desconsidera causas biológicas e sociais |
| Unicausal (Koch) | Doença causada por agente único | Ignora a tríade ecológica |
| Multicausal / Tríade Ecológica | Agente + Hospedeiro + Ambiente | Ainda focado no biológico |
| Determinação Social | Condições de vida e trabalho estruturam o perfil epidemiológico | Dificuldade de operacionalização clínica |

