## Relevância Clínica e Acadêmica

A criação do SUS não foi um ato espontâneo do Estado — foi o resultado de uma batalha política organizada por médicos, sanitaristas, comunidades e movimentos sociais que, no contexto da redemocratização, acreditaram que saúde poderia ser um direito universal no Brasil. Compreender a Reforma Sanitária e a 8ª Conferência Nacional de Saúde é fundamental para entender os princípios e as fragilidades do SUS atual. A Uninove cobra esse conteúdo diretamente e como contextualização de questões sobre princípios do SUS.

---

## 1. Contexto da Redemocratização (1985–1988)

Com o fim do Regime Militar, o Brasil vivenciou um intenso movimento de participação política. No campo da saúde, o INAMPS estava em colapso financeiro, e o modelo hospitalocêntrico/privatizante havia produzido uma crise de assistência: filas enormes, hospitais sobrelotados, exclusão de 40% da população.

| Problema no final do Regime Militar | Consequência para a sociedade |
|-------------------------------------|-------------------------------|
| INAMPS com dívida crescente | Hospitais não recebiam pelo atendimento |
| Exclusão de trabalhadores informais e rurais | Busca por pronto-socorro sem cobertura |
| Modelo hospitalar curativo | Doenças evitáveis não eram prevenidas |
| Cenários de epidemias (dengue, cólera) | Colapso da vigilância epidemiológica |

---

## 2. Movimento pela Reforma Sanitária Brasileira

O **Movimento pela Reforma Sanitária** reuniu sanitaristas, acadêmicos da USP, UNICAMP e UFRJ, profissionais de saúde, sindicatos e movimentos populares. Suas ideias centrais:

1. **Saúde como direito de cidadania e dever do Estado** (não como privilégio do trabalho formal)
2. **Determinação social da doença** — não basta tratar, é preciso agir nas condições de vida
3. **Municipalização e descentralização** do sistema de saúde
4. **Participação popular** no controle das políticas de saúde

Figuras centrais: **Sérgio Arouca** (ideólogo principal), **Hésio Cordeiro** (criador do INAMPS em processo de transformação), **David Capistrano** e o Centro Brasileiro de Estudos de Saúde (**CEBES**).

---

## 3. A 8ª Conferência Nacional de Saúde (1986)

A **8ª CNS** (março de 1986, Brasília) foi o marco mais importante da Reforma Sanitária. Pela primeira vez, a Conferência foi aberta à participação popular — não era restrita a técnicos e burocratas.

**Protagonista:** Sérgio Arouca presidiu a 8ª CNS.

**Resultados:**
- Aprovação do conceito ampliado de saúde (condições de vida)
- Proposta de criação do Sistema Único de Saúde (SUS)
- Princípios que foram incorporados à Constituição de 1988: universalidade, equidade, integralidade, descentralização, participação social

| O que a 8ª CNS não era | O que a 8ª CNS foi |
|------------------------|--------------------|
| Um evento técnico fechado | Participação de 4.000 delegados (profissionais, gestores, usuários) |
| Recomendação sem efeito | Base para a seção de Saúde na Constituição (art. 196-200) |
| Defesa do status quo | Ruptura com o modelo meritocrático e privatizante |

---

## 4. O SUDS como Transição (1987)

Antes da promulgação da Constituição, o governo Sarney criou o **SUDS** (Sistema Unificado e Descentralizado de Saúde) em 1987 como medida transitória. O SUDS transferiu serviços do INAMPS para os estados — foi o ensaio da descentralização que o SUS formalizaria depois.

---

## 5. A Constituição Federal de 1988 e a Criação do SUS

A **Constituição Federal de 1988** ("Constituição Cidadã") incorporou as conquistas da Reforma Sanitária na **Seção II — Da Saúde (artigos 196 a 200)**:

- **Art. 196:** "A saúde é direito de todos e dever do Estado..."
- **Art. 197:** Define as ações e serviços de saúde como de relevância pública
- **Art. 198:** Cria o SUS com suas diretrizes (descentralização, atendimento integral, participação comunitária)
- **Art. 199:** Permite a participação da iniciativa privada em caráter complementar
- **Art. 200:** Atribuições do SUS (vigilância sanitária, epidemiológica, saúde do trabalhador, etc.)

---

## Erros Clássicos em Prova (Uninove)

- **A 8ª CNS criou o SUS:** errado — a 8ª CNS propôs o SUS; quem criou foi a Constituição de 1988, regulamentada pela Lei 8.080/90.
- **Sérgio Arouca escreveu a Lei 8.080:** Arouca foi o ideólogo da Reforma Sanitária, não o autor das Leis Orgânicas (que vieram depois).
- **O SUDS foi o SUS:** o SUDS (1987) foi uma medida transitória pré-constitucional; o SUS é constitucional.
- **Reforma Sanitária = apenas médicos:** o movimento incluiu sindicatos, movimentos populares, partidos de oposição e academia — era um movimento social amplo.
- **Art. 196 define os princípios:** os princípios (universalidade, integralidade, equidade) estão no Art. 198; o Art. 196 é a definição de saúde como direito e dever do Estado.

