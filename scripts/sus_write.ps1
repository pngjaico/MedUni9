## Relevância Clínica e Acadêmica

O **Pacto pela Saúde (2006)** foi a maior reforma de gestão do SUS desde sua criação — substituiu o modelo de habilitação municipios/estados (NOBs) por um modelo de pactuação de metas. O **Pacto pela Vida** é o componente mais cobrado nas provas porque traz prioridades concretas de saúde pública com indicadores definidos. Conhecer suas 6 prioridades originais é essencial para questões que perguntam "qual é a diretriz/meta do Pacto pela Vida" ou para compreender a lógica dos programas de APS.

O Pacto se divide em três componentes: **pela Vida**, **em Defesa do SUS** e **pela Gestão** — cada um abordado em aulas separadas.

---

## 1. O Pacto pela Saúde (Portaria GM/MS 399/2006)

O Pacto pela Saúde foi uma iniciativa do Ministério da Saúde durante o governo Lula para reorganizar responsabilidades entre as esferas de governo, substituindo o sistema de habilitação por Termos de Compromisso de Gestão (TCG).

| Aspecto | NOBs (modelo anterior) | Pacto pela Saúde (2006) |
|---------|------------------------|--------------------------|
| Instrumento | Habilitação por portaria | Termo de Compromisso de Gestão (TCG) |
| Foco | Capacidade técnica e financeira | Pactuação de metas e responsabilidades |
| Relação entre entes | Hierárquica/certificatória | Cooperativa e ascendente |
| Indicadores | Poucos, financeiros | Múltiplos, por área temática |

---

## 2. Pacto pela Vida — As 6 Prioridades Originais

| Prioridade | Descrição |
|------------|-----------|
| **1. Saúde do Idoso** | Implantação da Política Nacional de Saúde da Pessoa Idosa; atenção às doenças crônicas não transmissíveis; prevenção de quedas e fraturas |
| **2. Controle do Câncer de Colo do Útero e de Mama** | Ampliação da cobertura do Papanicolau; rastreamento do câncer de mama com mamografia |
| **3. Redução da Mortalidade Infantil e Materna** | Redução dos índices de mortalidade neonatal, infantil e materna; qualificação do pré-natal e assistência ao parto |
| **4. Fortalecimento da Capacidade de Resposta às Doenças Emergentes e Endemias** | Dengue, malária, tuberculose, hanseníase, influenza |
| **5. Promoção da Saúde** | Implantação da Política Nacional de Promoção da Saúde (PNPS); redução de tabagismo, sedentarismo, alimentação inadequada |
| **6. Fortalecimento da Atenção Básica** | Ampliação da ESF; qualificação da APS como ordenadora do sistema |

> **Mnemônico para as 6 prioridades:** **I-CA-MOR-DE-PRO-AB**
> **I**doso | **Ca**ncer (colo e mama) | **Mor**talidade (infantil/materna) | **De**nge e endemias | **Pro**moção da saúde | **A**tenção **B**ásica

---

## 3. Indicadores do Pacto pela Vida

O Pacto foi o primeiro modelo a exigir **metas quantificáveis** para os municípios e estados no Termo de Compromisso de Gestão. Exemplos de indicadores:

| Área | Indicador exemplo |
|------|-------------------|
| Saúde do Idoso | Taxa de mortalidade por doenças cerebrovasculares em maiores de 60 anos |
| Câncer colo | Razão de exames citopatológicos cérvico-vaginais em mulheres de 25 a 64 anos |
| Mortalidade infantil | Taxa de mortalidade infantil por 1.000 nascidos vivos |
| Atenção Básica | Cobertura da Estratégia Saúde da Família (%) |

---

## 4. Por que o Pacto substituiu as NOBs?

As **NOBs** (Normas Operacionais Básicas) dos anos 90 — NOB 91, 93 e 96 — e a **NOAS 2001/2002** definiram as regras de financiamento e habilitação dos municípios. O problema: o sistema de habilitação criou municípios "plenos" e "parciais" sem alterar resultados de saúde. O Pacto de 2006 focou em **responsabilidades** e **resultados**, não em categorias de habilitação.

