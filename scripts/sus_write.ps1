## Relevância Clínica e Acadêmica

O SUS não nasceu do nada — ele é o produto de mais de 500 anos de disputas políticas sobre quem merece ter saúde no Brasil. Conhecer esse percurso é essencial para entender por que o SUS funciona como funciona hoje, quais são suas fragilidades históricas (subfinanciamento, centralização) e por que a Reforma Sanitária foi tão revolucionária. A Uninove cobra esse conteúdo com frequência em contextualização histórica e em questões que exigem sequenciar cronologicamente os modelos de saúde brasileiros.

Este tema é o alicerce para as aulas 3 e 4, onde a criação formal do SUS e suas leis serão abordadas.

---

## 1. Brasil Colonial e Imperial (1500–1889)

No período colonial não havia política de saúde estruturada. A assistência era prestada por **Santas Casas de Misericórdia** (primeira em Santos, 1543) e por práticas de curandeiros indígenas e africanos. O Estado não intervinha.

| Período | Característica principal |
|---------|--------------------------|
| Colonial | Santas Casas como único recurso; ausência do Estado |
| Imperial | Medidas sanitárias portuárias para proteger o comércio, não a população |
| Final do Império | Início das campanhas contra epidemias (varíola, febre amarela) |

A **saúde era privilégio de poucos** — negros escravizados e pobres ficavam à margem de qualquer assistência formal.

---

## 2. Primeira República e Sanitarismo Campanhista (1889–1930)

Com a expansão do modelo agroexportador, a saúde da força de trabalho passou a interessar ao Estado. **Oswaldo Cruz** realizou a famosa campanha de varíola no Rio de Janeiro (1904), que culminou na **Revolta da Vacina** — resposta popular à vacinação obrigatória imposta sem diálogo.

**Sanitarismo campanhista:** modelo autoritário, focado em doenças infecciosas, usando força policial para executar medidas (desinfecção de casas, vacinação compulsória). Contexto: proteger o porto do Rio de Janeiro para o comércio externo.

| Personagem | Contribuição |
|------------|--------------|
| Oswaldo Cruz | Combate à varíola, febre amarela e peste bubônica; Revolta da Vacina (1904) |
| Carlos Chagas | Descoberta da doença de Chagas (1909); integrou saúde rural à política nacional |

Em 1923, a **Lei Eloy Chaves** criou as **Caixas de Aposentadorias e Pensões (CAPs)** — primeiro sistema previdenciário brasileiro, organizado por empresa, não pelo Estado. É o embrião da relação entre trabalho formal e acesso à saúde que persiste até hoje.

---

## 3. Era Vargas e o IAPS (1930–1945)

Getúlio Vargas transformou as CAPs nos **Institutos de Aposentadorias e Pensões (IAPs)**, organizados por categoria profissional (IAPM para marítimos, IAPI para industriários, etc.). O MESP (Ministério da Educação e Saúde Pública) foi criado em 1930.

Características do modelo Vargas:
- Saúde vinculada ao trabalho formal — quem não trabalhava com carteira assinada ficava sem assistência
- Cresceu a oferta de serviços hospitalares para trabalhadores contribuintes
- População rural e desempregados dependiam de caridade ou nada

---

## 4. Redemocratização e Desenvolvimentismo (1945–1963)

Criação do **Ministério da Saúde** separado em 1953 (antes era Ministério da Educação e Saúde). Em 1956, criação da **SUCAM** (Superintendência de Campanhas de Saúde Pública) para doenças endêmicas.

O modelo permanecia **dual:** trabalhadores formais com IAPs, restante da população com serviços públicos precários ou Santas Casas.

---

## 5. Regime Militar e a INAMPS (1964–1984)

Em 1966, a ditadura militar unificou todos os IAPs no **INPS** (Instituto Nacional de Previdência Social), e depois criou o **INAMPS** (Instituto Nacional de Assistência Médica da Previdência Social) em 1974.

| Aspecto | Característica |
|---------|----------------|
| Modelo assistencial | Hospitalar, curativo, privatizante — contratação de hospitais privados pelo Estado |
| Cobertura | Apenas trabalhadores com carteira assinada e dependentes |
| Exclusão | 40% da população (trabalhadores rurais, informais, desempregados) sem acesso |
| Financiamento | Folha de salários + contribuição patronal (tripartite: trabalhador, empresa, Estado) |

O Regime Militar aprofundou a **privatização da saúde**: o Estado comprava serviços da iniciativa privada em vez de construir infraestrutura pública. Isso criou um setor privado hospitalar poderoso que ainda hoje exerce pressão política sobre o SUS.

---

## Erros Clássicos em Prova (Uninove)

- **CAPs vs. IAPs:** CAPs (1923) eram por empresa; IAPs (Vargas) eram por categoria profissional — é a diferença mais cobrada na cronologia.
- **Revolta da Vacina como resistência sanitária:** a Revolta foi reação à vacinação compulsória autoritária, não contra a vacina em si — o contexto político importa.
- **INAMPS = único sistema de saúde do Brasil:** não — o INAMPS só cobria trabalhadores formais; a maioria da população não tinha cobertura garantida.
- **Oswaldo Cruz vs. Carlos Chagas:** Oswaldo Cruz fez campanhas no Rio de Janeiro (varíola/febre amarela); Chagas descobriu a tripanossomíase e depois dirigiu o que seria a Fiocruz.
- **Ministério da Saúde criado em 1930:** errado — em 1930 foi criado o Ministério da Educação e Saúde Pública; o Ministério da Saúde separado só surgiu em 1953.

