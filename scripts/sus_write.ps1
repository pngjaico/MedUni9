# SUS — Aula 4: O SUS e as Leis Orgânicas da Saúde

**Disciplina:** Princípios e Diretrizes do SUS
**Módulo:** 1 | **Tempo de estudo sugerido:** 10-15 min

---

## Relevância Clínica e Acadêmica

As Leis 8.080/90 e 8.142/90 são a "constituição interna" do SUS — traduzem os artigos 196 a 200 da CF/88 em regras operacionais concretas. Em provas da Uninove, questões sobre princípios doutrinários vs. organizativos, sobre financiamento e sobre participação social quase sempre têm sua resposta correta ancorada nessas duas leis. O médico que conhece a Lei 8.080 entende não apenas as regras do sistema, mas a lógica filosófica que move a APS brasileira.

---

## 1. Lei 8.080/90 — Lei Orgânica da Saúde

Regulamenta o art. 198 da CF/88. Define condições para promoção, proteção e recuperação da saúde; organização e funcionamento dos serviços.

### Princípios Doutrinários (filosofia do SUS)

| Princípio | Definição |
|-----------|-----------|
| **Universalidade** | Saúde é direito de TODOS os brasileiros, independente de renda, raça, trabalho ou plano de saúde |
| **Integralidade** | Atenção à saúde em todas as dimensões: promoção, proteção, reabilitação; do individual ao coletivo |
| **Equidade** | Tratar desigualmente os desiguais — priorizar quem mais precisa para reduzir iniquidades |

### Princípios Organizativos (como o SUS se estrutura)

| Princípio | Definição |
|-----------|-----------|
| **Descentralização** | Cada esfera de governo (federal, estadual, municipal) tem responsabilidades próprias; ênfase na municipalização |
| **Regionalização** | Organização dos serviços por território com referência e contrarreferência |
| **Hierarquização** | Organização em níveis de complexidade: AB → Média Complexidade → Alta Complexidade |
| **Participação social** | Conselhos e Conferências de Saúde com poder deliberativo |
| **Resolubilidade** | Cada nível deve resolver o que é de sua competência |

> **Dica de prova:** Universalidade, Integralidade e Equidade = doutrinários (UNI-IN-EQU).
> Descentralização, Regionalização, Hierarquização = organizativos.

### Outros artigos relevantes da Lei 8.080

- **Financiamento tripartite:** União, estados e municípios financiam o SUS conjuntamente
- **Competências por esfera:** União formula política nacional + financia + fiscaliza; Municípios executam as ações de saúde
- **Campo de atuação:** inclui vigilância sanitária, vigilância epidemiológica, saúde do trabalhador, saúde ambiental

---

## 2. Lei 8.142/90 — Participação Social e Financiamento

A Lei 8.142 complementa a 8.080 em dois pontos cruciais que ficaram de fora (foram vetados por Collor na 8.080 e depois regulamentados separadamente):

### Participação Social

| Instância | Composição | Periodicidade | Função |
|-----------|------------|---------------|--------|
| **Conselho de Saúde** | 50% usuários + 25% trabalhadores + 25% gestores/prestadores | Permanente (mensal) | Deliberativo — aprova orçamento e plano de saúde |
| **Conferência de Saúde** | Representantes da sociedade | A cada 4 anos | Avalia e propõe diretrizes para a política de saúde |

> A composição paritária do Conselho é a mais cobrada: **50% de usuários** — essa maioria é garantida para evitar cooptação pelo setor privado.

### Transferências Financeiras (Fundo a Fundo)

- Os recursos federais para estados e municípios devem ser transferidos diretamente do **Fundo Nacional de Saúde** para os **Fundos Estaduais e Municipais de Saúde**
- Para receber os repasses, o município deve ter: **Fundo Municipal de Saúde + Conselho Municipal de Saúde + Plano Municipal de Saúde + Relatório de Gestão**

---

## 3. Diferença entre as duas leis

| Aspecto | Lei 8.080/90 | Lei 8.142/90 |
|---------|-------------|-------------|
| Foco | Organização do sistema, princípios, competências | Participação social e financiamento/transferências |
| Origem | Regulamentação do Art. 198 CF/88 | Complementação após vetos de Collor na 8.080 |
| Pontos mais cobrados | Princípios doutrinários vs. organizativos | Composição do Conselho (50% usuários), Fundo a Fundo |

