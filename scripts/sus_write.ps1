## 2. Determinantes Sociais de Saúde (DSS)

**Determinantes Sociais de Saúde** são as condições sociais em que as pessoas nascem, crescem, vivem, trabalham e envelhecem. O conceito foi consolidado pela **Comissão Nacional de DSS (CNDSS, 2008)** e pelo relatório da OMS coordenado por **Michael Marmot** (Comissão sobre Determinantes Sociais da Saúde, 2008).

### Modelo de Dahlgren e Whitehead (1991)

O modelo mais cobrado nas provas representa camadas concêntricas ao redor do indivíduo:

| Camada | Exemplos |
|--------|----------|
| Características individuais (núcleo) | Idade, sexo, herança genética |
| Estilo de vida | Tabagismo, sedentarismo, alimentação |
| Redes sociais e comunitárias | Apoio familiar, coesão social, capital social |
| Condições de vida e trabalho | Moradia, emprego, educação, serviços de saúde |
| Macrodeterminantes | Política econômica, cultura, urbanização, ambiente |

A importância do modelo está em demonstrar que fatores estruturais (economia, urbanização) impactam mais a saúde do que comportamentos individuais. O médico de família atua em TODAS as camadas, não apenas na mais interna.

### Gradiente Social de Saúde (Marmot)

A saúde piora progressivamente conforme a posição na hierarquia social decresce. Não é só pobreza extrema — a diferença entre classe média-baixa e média-alta já produz diferenças mensuráveis em expectativa de vida e morbidade. Isso é o **gradiente social de saúde**, documentado nos Estudos de Whitehall (funcionários públicos britânicos).

---

## 3. Vulnerabilidade em Saúde

**Vulnerabilidade** é a suscetibilidade de indivíduos ou grupos a danos à saúde, resultante da interação entre dimensões individuais, sociais e programáticas.

| Dimensão | Descrição | Exemplo prático |
|----------|-----------|-----------------|
| Individual | Conhecimento, comportamento, recursos pessoais | Adolescente com baixa escolaridade sobre ISTs |
| Social | Relações de poder, gênero, raça, renda | Mulher negra em situação de violência doméstica |
| Programática (institucional) | Acesso e qualidade dos serviços de saúde | UBS sem médico na zona rural |

A vulnerabilidade não é atributo fixo — muda com o contexto. O conceito surgiu nos estudos de HIV/AIDS com **Jonathan Mann** e foi incorporado à saúde pública brasileira como ferramenta de planejamento.

---

## 4. Iniquidades em Saúde

**Iniquidade em saúde** é a diferença de saúde entre grupos que é injusta e evitável. Difere de **desigualdade** (qualquer diferença mensurável) por ser moralmente inaceitável e corrigível por políticas públicas.

| Conceito | Definição |
|----------|-----------|
| Desigualdade em saúde | Diferença mensurável de indicadores entre grupos populacionais |
| Iniquidade em saúde | Desigualdade que é injusta, socialmente determinada e evitável |
| Equidade em saúde | Meta de política pública: tratar desigualmente os desiguais para reduzir iniquidades |

**Equidade** é um princípio do SUS — não é tratar todos iguais, mas priorizar quem mais precisa (populações vulneráveis, territórios de maior risco).

---

## Erros Clássicos em Prova (Uninove)

- **Igualdade vs. equidade:** igualdade = mesma coisa para todos; equidade = mais para quem precisa mais. A Uninove costuma inverter nas alternativas: "o SUS garante igualdade" — errado, garante equidade.
- **DSS são só comportamento individual:** DSS inclui estrutura socioeconômica, política e cultural — tabagismo e sedentarismo são apenas a camada de estilo de vida, não o universo dos DSS.
- **Definição da OMS é suficiente:** a definição é cobrada, mas a crítica (utópica, estática) também cai. Saiba os dois lados.
- **Camadas de Dahlgren-Whitehead:** a genética fica no núcleo (não é modificável como DSS); as políticas econômicas são a camada mais externa (macrodeterminantes) — não confundir a ordem.
- **Iniquidade = desigualdade:** toda iniquidade é uma desigualdade, mas nem toda desigualdade é iniquidade. A distinção está em ser evitável e injusta.

