## 1. Cavidade Oral — Limites e Subdivisões

| Estrutura | Limites |
|-----------|---------|
| **Vestíbulo bucal** | Entre dentes/gengivas e lábios/bochechas |
| **Cavidade oral propriamente dita** | Dentro dos dentes; teto = palato; assoalho = diafragma oral (músculo milo-hióideo + geniohióideo) |
| **Comunicação com faringe** | Istmo das fauces (delimitado pelos pilares palatoglossais) |

---

## 2. Palato e Úvula

| Parte | Composição | Função |
|-------|-----------|--------|
| **Palato duro** | Processos palatinos dos maxilares + lâminas horizontais do palatino; revestimento mucoso | Separação de boca e nariz; apoio para mastigação |
| **Palato mole (véu palatino)** | Músculo; sem ossificação | Fechamento da nasofaringe durante deglutição (músculo levantador do véu) |
| **Úvula** | Projeção do palato mole | Ajuda a fechar nasofaringe; reflexo de vômito |

