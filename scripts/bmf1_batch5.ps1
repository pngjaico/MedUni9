## Ponte com a Clínica

No exame neurológico, pede-se ao paciente que protaia a língua: ela desvia para o lado da lesão do hipoglosso (XII). O genioglosso contralateral ao lado lesado empurra a língua para o lado lesado. Em lesão da base do crânio ou tumor do pescoço, o XII pode ser comprometido. Na caxumba (parotidite viral), a parótida fica inflamada — e como o nervo facial (VII) passa dentro dela, pode haver paresia facial como complicação. Esses conceitos são cobrados tanto em anatomia quanto em semiologia.

