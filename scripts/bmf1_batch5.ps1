## Erros Clássicos em Prova (Uninove)

- **Glândula sebácea = apócrina:** sebácea é HOLÓCRINA (a célula inteira vira o sebo). Apócrina são as sudoríparas da axila.
- **Sudorípara écrina em toda a pele = regulação de temperatura:** correto, mas cuidado — as APÓCRINAS não têm papel na termorregulação, só nas écrinas.
- **Parótida é mista (mucosa + serosa):** parótida é PURA SEROSA. Mista = submandibular (com predominância mucosa). Sublingual = predominante mucosa.
- **Pâncreas é glândula endócrina:** o pâncreas é uma glândula MISTA — exócrino (ácinos serosos com enzimas) + endócrino (ilhotas de Langerhans com insulina/glucagon).
