## Relevância Clínica e Acadêmica

Esta aula de prática consolida a identificação histológica das estruturas da pele em lâminas e relaciona os achados histológicos com patologias relevantes. A prova da Uninove usa imagens de lâminas e pede para identificar camadas da epiderme, glândulas cutâneas, folículo piloso e tecido adiposo. Dominar esta identificação visual também prepara para entender biópsia de pele — o exame definitivo em dermatologia.

---

## 1. Identificação das Camadas da Pele na Lâmina

### Epiderme (de fora para dentro):
| Camada | O que ver na lâmina | Dica visual |
|--------|---------------------|------------|
| **Córnea** | Lâminas acidófilas (rosas), sem núcleos | Mais superficial, "escamas" cor-de-rosa |
| **Lúcida** | Faixa pálida translúcida (só em pele espessa) | Entre córnea e granulosa — presente em palma/planta |
| **Granulosa** | Grânulos basofílicos (querato-hialina) no citoplasma | Células em processo de morte com grânulos escuros |
| **Espinhosa** | Células poliédricas com projeções ("espinhos") | Maior em número em pele espessa |
| **Basal** | Coluna de células cúbicas/cilíndricas sobre MB | Camada mais profunda — melanócitos intercalados |

### Derme (logo abaixo da MB):
- **Derme papilar:** conjuntivo frouxo, rica em fibras reticulares; forma papilas que interdigitam com a epiderme
- **Derme reticular:** conjuntivo denso não modelado; colágeno tipo I espesso; resistência mecânica

### Hipoderme (tela subcutânea):
- Tecido adiposo (células com grande vacúolo lipídico, núcleo periférico) + septos de conjuntivo fibroso

