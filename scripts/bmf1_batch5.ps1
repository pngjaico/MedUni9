| **Célula de Langerhans** | Camada espinhosa | Célula dendrítica apresentadora de antígeno; imunidade cutânea | Histiocitose de células de Langerhans |
| **Célula de Merkel** | Camada basal | Mecanorreceptor (tato fino, discriminação de forma) | Carcinoma de Merkel (raro, agressivo) |

