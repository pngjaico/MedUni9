## Erros Clássicos em Prova (Uninove)

- **Melancócito = pigmentação na camada espinhosa:** o corpo do melanócito fica na camada BASAL; mas os dendritos transportam melanossomos para os queratinócitos da espinhosa.
- **Gordura marrom só em neonatos:** adultos também têm nas regiões cervicais e mediastinais — é alvo de pesquisa para obesidade e termogênese (UCP-1).
- **Músculo eretor do pelo = músculo esquelético:** é músculo LISO (involuntário) — controlado pelo sistema simpático; causa piloereção ("arrepios").
- **Célula de Langerhans vem da epiderme:** Langerhans são macrófagos/células dendríticas derivadas da medula óssea que migraram para a epiderme.
- **Derme papilar = conjuntivo denso:** derme papilar = conjuntivo FROUXO (camada mais superficial). Derme reticular = conjuntivo DENSO não modelado.

