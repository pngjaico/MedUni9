## Relevância Clínica e Acadêmica

A cavidade oral é o início do trato digestório e uma janela de diagnóstico — candidíase oral revela imunodeficiência, leucoplasia alerta para câncer, halitose indica doenças sistêmicas. Anatomia da faringe é fundamental para entender a intubação orotraqueal, o manejo de via aérea em emergências e a deglutição. Nervo hipoglosso (XII) e glossofaríngeo (IX) são testados em exame neurológico e cobrados na correlação com lesão craniana.

