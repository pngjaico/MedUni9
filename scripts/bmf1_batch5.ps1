| **Hioglosso** | Retrai e abaixa a língua | Hipoglosso (XII) |
| **Estiloglosso** | Retrai e eleva | Hipoglosso (XII) |
| **Palatoglosso** | Eleva o dorso; fecha istmo | Plexo faríngeo (X + XI acessório) |

> **Todos os músculos da língua** (exceto o palatoglosso) são inervados pelo **nervo hipoglosso (XII)**.

