- **Ducto de Wharton abre na parótida:** ducto de Wharton = submandibular (abre no frênulo). Ducto de Stensen = parótida (abre no vestíbulo molar superior).
- **Papilas filiformes têm paladar:** papilas filiformes são as mais numerosas, mas NÃO têm cálices gustativos — função tátil apenas.
- **Parótida é mista:** parótida é serosa PURA. Submandibular é mista.

