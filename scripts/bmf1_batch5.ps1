## Relevância Clínica e Acadêmica

O tecido epitelial glandular é a base de toda secreção do organismo: hormônios, enzimas digestivas, leite materno, suor, sebo, lágrimas. Cada tipo glandular tem características morfológicas que determinam sua função — e que a Uninove cobra especialmente na distinção entre glândulas exócrinas (com ducto) e endócrinas (sem ducto), e nos mecanismos de secreção (merócrina, apócrina, holócrina). Conhecer esses mecanismos permite entender a patologia da glândula mamária, das sebáceas e das sudoríparas.

---

## 1. Glândulas Exócrinas vs. Endócrinas

| Característica | Glândula Exócrina | Glândula Endócrina |
|----------------|-------------------|-------------------|
| **Ducto** | Sim — produto liberado em superfície epitelial | Não — produto liberado diretamente no sangue |
| **Produto** | Secreções externas: enzimas, muco, suor, sebo, leite | Hormônios |
| **Exemplos** | Glândula salivar, sudorípara, mamária, sebácea, pancreática exócrina | Hipófise, tireoide, suprarrenal, pâncreas endócrino (ilhotas de Langerhans) |

---

## 2. Glândulas Exócrinas — Classificação Morfológica

### Por forma da porção secretora

| Tipo | Forma | Exemplo |
|------|-------|---------|
| **Tubulosa** | Tubo simples ou enovelado | Glândula de Lieberkühn (intestino), sudorípara écrinas (enoveladas) |
| **Alveolar (acinar)** | Bolsa/esfera | Glândula sebácea |
| **Tubuloalveolar** | Misto de tubo + alvéolo | Glândula mamária, glândula submandibular, parótida |

