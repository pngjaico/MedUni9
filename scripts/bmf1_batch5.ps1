## 2. Estruturas da Pele Identificáveis em Lâmina

| Estrutura | Como identificar | Tipo de glândula/célula |
|-----------|------------------|------------------------|
| **Glândula sudorípara écrina** | Glomérulo enovelado na derme profunda/hipoderme; célula piramidal com lúmen | Tubulosa simples enovelada; merócrina |
| **Glândula sudorípara apócrina** | Lúmen maior; secretária colunar com projeções apicais; localizada mais profundamente | Tubulosa simples; apócrina |
| **Glândula sebácea** | Ácinos ligados ao folículo piloso; células cheias de lipídeos (claras); sem lúmen central nítido | Alveolar; holócrina |
| **Folículo piloso** | Invaginação da epiderme; haste do pelo; bainha radicular interna/externa | Conjunto epiderme + teca | 
| **Músculo eretor do pelo** | Fascículo de músculo liso ligando a bainha folicular à derme papilar | Músculo liso (arreterctor pili) |

