## 4. Células Especiais da Epiderme

| Célula | Localização | Função | Patologia |
|--------|-------------|--------|-----------|
| **Queratinócito** | Todas as camadas (maioria) | Produz queratina (barreira) | Carcinoma basocelular (células basais), carcinoma espinhocelular (células espinhosas) |
