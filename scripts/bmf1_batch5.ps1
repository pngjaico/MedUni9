## 3. Tecido Adiposo — Tipos

| Tipo | Localização | Características na lâmina | Função |
|------|-------------|--------------------------|--------|
| **Unilocular (amarelo)** | Subcutâneo, mesentério, retroperitôneo | Célula com 1 grande vacúolo lipídico; núcleo na periferia (forma de anel de sinete) | Reserva energética, isolamento térmico, proteção mecânica |
| **Multilocular (marrom)** | Interescapular e perirrenal no neonato; adulto: pescoço e mediastino | Múltiplos vacúolos; núcleo central; rica vascularização | Termogênese sem tremor (proteína desacoplante UCP-1) |

