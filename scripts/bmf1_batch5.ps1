### O que você PRECISA saber

- **Língua — motor:** hipoglosso (XII) para todos, exceto palatoglosso (X/XI)
- **Língua — sensitivo 2/3 anteriores:** lingual (V3) = tato; corda tímpano (VII) = paladar
- **Língua — sensitivo 1/3 posterior:** glossofaríngeo (IX) = tato E paladar
- **Parótida:** serosa, ducto Stensen (2º molar sup.), nervo facial passa por dentro
- **Submandibular:** mista, ducto Wharton (frênulo lingual)
- **Faringe:** naso + oro + laringofaringe
- **Papila caliciforme:** caliciformes têm cálices gustativos; filiformes NÃO

