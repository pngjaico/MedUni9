## Relevância Clínica e Acadêmica

Saber quais artérias suprem cada segmento do intestino é crítico para entender isquemia mesentérica — uma emergência cirúrgica com alta mortalidade. A divisão entre território da artéria mesentérica superior (AMS) e inferior (AMI) explica onde aparecem as isquemias e ditam os limites da ressecção cirúrgica. A inervação entérica também explica a dor referida de órgãos viscerais e o funcionamento reflexo do intestino (plexo de Auerbach e Meissner).

---

## 1. Artérias do Trato Gastrointestinal

### Tronco celíaco (saída: T12-L1 da aorta)
| Ramo | Território |
|------|-----------|
| **Artéria gástrica esquerda** | Curvatura menor do estômago; parte do esôfago distal |
| **Artéria hepática (comum → própria)** | Fígado, vesícula biliar (cística da hepática direita), duodeno (gastroduodenal) |
| **Artéria esplênica** | Baço; cauda do pâncreas; curvatura maior do estômago (gastroepiploica esquerda) |

> Resumo do tronco celíaco: estômago, esôfago distal, fígado, vesícula, baço, pâncreas (maior parte), duodeno proximal.

### Artéria Mesentérica Superior (AMS — saída: L1)
| Ramo | Território |
|------|-----------|
| **Artéria pancreaticoduodenal inferior** | Duodeno distal + cabeça do pâncreas |
| **Ramos jejunais e ileais** | Jejuno e íleo (12-15 ramos em arcos) |
| **Artéria ileocólica** | Íleo terminal, ceco, apêndice |
| **Artéria cólica direita** | Cólon ascendente |
| **Artéria cólica média** | 2/3 direitos do cólon transverso |

### Artéria Mesentérica Inferior (AMI — saída: L3)
| Ramo | Território |
|------|-----------|
| **Artéria cólica esquerda** | 1/3 esquerdo cólon transverso + cólon descendente |
| **Artérias sigmoideas** | Cólon sigmoide |
| **Artéria retal superior** | Reto superior (1/3 superior do reto) |

### Ponto de Griffiths
A anastomose entre artéria cólica média (AMS) e artéria cólica esquerda (AMI) é chamada **ponto de Griffiths** (ângulo esplênico do cólon) — zona de baixo fluxo, vulnerável a isquemia. Também: **ponto de Sudeck** = anastomose entre retal superior (AMI) e retal média (ilíaca interna), no sigmoide distal.

---

## 2. Drenagem Venosa — Sistema Porta

| Veia | Drena |
|------|-------|
| **Veia mesentérica superior** | Intestino delgado, cólon direito, estômago (via gastroepiploica direita) |
| **Veia esplênica** | Baço, pâncreas; recebe veia mesentérica inferior |
| **Veia porta** | Formada por mesentérica superior + esplênica; entra no fígado pelo hilo |
| **Veia mesentérica inferior** | Desemboca na esplênica |

> **Sistema porta:** o sangue do intestino e estômago vai ao fígado antes de chegar à circulação sistêmica (metabolismo de 1ª passagem, detoxificação, nutrientes).

---

## 3. Inervação Autonômica do TGI

| Divisão | Nervo | Efeito no TGI |
|---------|-------|--------------|
| **Parassimático** | Vago (X) — esôfago ao ângulo esplên.; nervo pélvico (S2-S4) — descendente ao reto | Aumenta motilidade e secreção (digestão) |
| **Simpático** | Nervos esplâncnicos (T5-L2) → gânglios celíaco e mesentéricos | Diminui motilidade; contrai esfíncteres; vasoconstrição |

### Plexos entéricos (sistema nervoso entérico = "segundo cérebro")

| Plexo | Localização | Função |
|-------|-------------|--------|
| **Plexo de Auerbach (mioentérico)** | Entre muscular circular e longitudinal | Controle da motilidade (peristaltismo) |
| **Plexo de Meissner (submucoso)** | Submucosa | Controle da secreção e absorção |

> **Doença de Hirschsprung:** ausência de células ganglionares no plexo de Auerbach/Meissner no cólon distal → espasmo do segmento afetado → obstipação desde o nascimento.

---

## 4. Dor Visceral Referida — Dermátomos

| Órgão | Dermatômico de referência | Nervos |
|-------|--------------------------|--------|
| Esôfago distal | T4-T5 | Esplâncnicos torácicos |
| Estômago / duodeno | T5-T9 (epigástrio) | Esplâncnicos |
| Intestino delgado | T9-T11 (umbilical) | Esplâncnico menor |
| Apêndice | T10 (umbilical) | Explica dor inicial em região umbilical |
| Cólon direito | T11-L1 | |
| Cólon esquerdo / sigmoide | L1-L2 | |
| Reto / pelve | S2-S4 (via nervo pélvico) | |

---

## Erros Clássicos em Prova (Uninove)

- **A AMI irriga o intestino delgado:** quem irriga o intestino delgado (jejuno e íleo) é a AMS. A AMI começa no cólon descendente.
- **Veia porta drain direto para o coração:** a veia porta vai ao fígado primeiro (metabolismo 1ª passagem). Depois, a circulação hepática drena pelas veias hepáticas para a VCI.
- **Plexo de Meissner controla motilidade:** Meissner = SUBMUCOSO = secreção. AUERBACH = mioentérico = motilidade.
- **Em isquemia mesentérica aguda, o cólon direito é poupado:** não — o cólon direito é irrigado pela AMS; uma oclusão aguda da AMS pode afetar desde o jejuno até o cólon transverso.
- **O vago inerva todo o TGI:** o vago (X) vai até o ângulo esplênico do cólon — o cólon descendente, sigmoide e reto são inervados pelo nervo pélvico (S2-S4).

---

