## 2. Especialidades Histológicas do Intestino Delgado

| Estrutura | Localização | Função |
|-----------|-------------|--------|
| **Pregas circulares (válvulas de Kerckring)** | Mucosa + submucosa; toda extensão; mais no jejuno | Aumenta área de absorção (~3x) |
