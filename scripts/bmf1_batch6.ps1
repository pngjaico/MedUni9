Da superfície para a profundidade:

| Camada | Estrutura |
|--------|-----------|
| 1 | Pele |
| 2 | Tela subcutânea (camada de Camper [gordura] + fáscia de Scarpa [membranosa]) |
| 3 | Músculo oblíquo externo (+ aponeurose) |
| 4 | Músculo oblíquo interno (+ aponeurose) |
| 5 | Músculo transverso do abdome (+ aponeurose) |
| 6 | Fáscia transversal |
| 7 | Gordura extraperitoneal |
| 8 | Peritônio parietal |

