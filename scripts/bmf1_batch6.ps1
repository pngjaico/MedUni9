## Relevância Clínica e Acadêmica

O intestino delgado é o maior sítio de absorção do organismo — anatomia das vilosidades e microvilosidades explica síndromes de má absorção (doença celíaca, doença de Crohn, ressecção intestinal). O intestino grosso é o sítio de câncer colorretal, o segundo tumor mais incidente em ambos os sexos no Brasil. A distinção anatômica entre cólon direito (irrigado pela mesentérica superior) e cólon esquerdo (mesentérica inferior) é essencial para entender isquemia colônica.

---

## 1. Intestino Delgado — Segmentos

| Segmento | Comprimento | Localização | Características |
|----------|-------------|-------------|----------------|
| **Duodeno** | ~25 cm (12 dedos) | Retroperitoneal (2ª-4ª partes) + intraperitoneal 1ª parte | Em C; ampola de Vater (papila duodenal maior) na 2ª parte; glândulas de Brunner (mucosas) no duodeno |
| **Jejuno** | ~2,5 m | Intraperitoneal; quadrante sup. esquerdo | Parede mais espessa; pregas circulares mais proeminentes; mais vilosidades; vermelho vivo; mesentério com menos gordura |
| **Íleo** | ~3,5 m | Intraperitoneal; quadrante inf. direito | Parede mais fina; menos pregas; placas de Peyer (tecido linfóide); mais gordura no mesentério |

