## Ponte com a Clínica

Na isquemia mesentérica aguda por embolia da AMS (mais comum em fibrilação atrial + êmbolo), o quadro é: dor abdominal intensa desproporcional ao exame físico (inicial — intestino isquêmico dói visceralmente, distendido, mas ainda sem peritonite). Com o tempo → necrose transmural → peritonite → choque. A angiotomografia confirma a oclusão. Saber que a AMS irriga jejuno, íleo, ceco e cólon direito permite estimar a extensão da ressecção necessária — e o risco de síndrome do intestino curto no pós-operatório.

