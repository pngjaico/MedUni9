## 4. Pâncreas — Anatomia

### Partes

| Parte | Localização | Peritoneal |
|-------|-------------|-----------|
| **Cabeça** | C do duodeno; intimamente ligada à 2ª porção duodenal | Retroperitoneal |
| **Corpo** | Atravessa a coluna vertebral (L1-L2) | Retroperitoneal |
| **Cauda** | Hilo do baço; no ligamento esplenorrenal | **Intraperitoneal** |

### Ductos pancreáticos
- **Ducto de Wirsung (principal):** corre ao longo do pâncreas; une-se ao colédoco → forma a **ampola hepatopancreática de Vater** → abre na papila duodenal maior
- **Ducto de Santorini (acessório):** drena parte da cabeça; abre na papila duodenal menor (2 cm acima da maior)
- **Esfíncter de Oddi:** músculo liso que controla o fluxo de bile e suco pancreático na ampola de Vater

### Relações anatômicas críticas
- A veia mesentérica superior passa atrás do pescoço do pâncreas — tumor de pâncreas encarcera a VMS → hipertensão portal sinistral
- O ducto biliar comum desce atrás/dentro da cabeça do pâncreas → carcinoma da cabeça causa icterícia obstrutiva progressiva (síndrome de Courvoisier: vesícula palpável + icterícia SEM dor)

---

## Erros Clássicos em Prova (Uninove)

- **Colédoco + ducto pancreático abrem na papila menor:** a papila MAIOR (Vater) recebe colédoco + Wirsung. A papila menor é onde abre o ducto acessório de Santorini.
- **Triângulo de Calot contém a veia porta:** o triângulo de Calot contém a artéria cística. A veia porta está no hilo hepático, não no calot.
- **O pâncreas é inteiramente retroperitoneal:** a cauda é INTRAPERITONEAL — é o único segmento que está dentro do ligamento esplenorrenal, junto ao hilo do baço.
- **Icterícia + dor intensa = câncer de pâncreas:** a tríade de Courvoisier (icterícia obstrutiva + vesícula palpável + SEM dor) sugere tumor de pâncreas. Icterícia COM dor sugere coledocolitíase.
- **Ducto cístico conecta diretamente o colédoco ao duodeno:** ducto cístico + ducto hepático comum = colédoco. O colédoco é que desemboca no duodeno.

