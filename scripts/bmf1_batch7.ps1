## Ponte com a Clínica

Na colonoscopia, o gastroenterologista avança o endoscópio pelo canal anal → reto → sigmoide → descendente → ângulo esplênico → transverso → ângulo hepático → ascendente → ceco (identifica a válvula ileocecal e percebe o apêndice como orifício aberto). Se identifica um pólipo no sigmoide e tira biópsia: histologia mostra glândulas sem vilosidades, mucosa com células caliciformes abundantes — confirmando que é cólon. Se o pólipo for no íleo terminal (intuba a válvula ileocecal), a biópsia mostrará placas de Peyer e algumas vilosidades. Diagnóstico histotopográfico é precisão baseada em anatomia.

