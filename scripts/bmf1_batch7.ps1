## Relevância Clínica e Acadêmica

Esta aula prática consolida a identificação dos órgãos digestórios em peças anatômicas, modelos plásticos e imagens (TC, RM, ecografia). A prova da Uninove frequentemente usa imagens de peças de cadáver ou cortes de TC para pedir identificação de estruturas. Dominar a correlação entre a posição anatômica descrita e a imagem correspondente é a diferença em questões que valem ponto.

---

## 1. Identificação em Peça — Roteiro Prático

### Passo 1: Orientar a peça
- Confirmar plano (anterior/posterior, superior/inferior)
- Identificar estruturas de referência: fígado (QSD), estômago (epigástrio/hipocôndrio esquerdo), cólon transverso (divide superior/inferior)

### Passo 2: Seguir o trajeto do TGI
Boca → Esôfago (retrotraqueal) → Estômago (incisura angular + piloro) → Duodeno (C em torno da cabeça do pâncreas) → Jejuno (QSE, alças de pregas proeminentes) → Íleo (QID, alças mais finas, placa de Peyer visível na mucosa) → Válvula ileocecal (fossa ilíaca direita) → Ceco + Apêndice → Cólon ascendente (direito) → Ângulo hepático → Cólon transverso → Ângulo esplênico → Cólon descendente (esquerdo) → Sigmoide → Reto → Canal anal

### Passo 3: Identificar o diferencial intestino delgado × grosso
| Característica | Intestino Delgado | Intestino Grosso |
|----------------|-------------------|-----------------|
| Calibre | Menor | Maior |
| Posição | Centro-abdome | Periferia ("moldura") |
| Haustrações | Não | Sim (no cólon) |
| Tênias | Não | Sim (3, visíveis no cólon) |
| Pregas de mucosa | Circulares (Kerckring), abundantes | Semilunar (haustrações) |

---

## 2. Correlação com Imagem por TC

| Estrutura | Como aparece na TC |
|-----------|-------------------|
| Fígado | Massa hiperdensa homogênea, QSD/epigástrio |
| Vesícula biliar | Oval anecoica no QSD (ecografia); cística hipodensa |
| Baço | Oval, QSE, atenuação similar ao fígado |
| Pâncreas | Horizontal, corpo na linha média (L1-L2), cauda ao baço |
| Rins | Retroperitoneais, flancos, peri-rrenais com gordura |
| Alças delgado | Centrais, calibre uniforme, parede fina |
| Cólon | Periférico, haustrações, pode conter gás |
| Apêndice | Cego QID, estrutura tubular cega (diâmetro normal <6 mm) |

---

## 3. Pontos de Referência Cirúrgica para a Prova

| Marco | Significado Clínico |
|-------|-------------------|
| **Ângulo de Treitz (ligamento suspensor do duodeno)** | Divide intestino alto (esôfago-estômago-duodeno-jejuno proximal) de intestino baixo → onde se define sangramento alto vs. baixo |
| **Válvula ileocecal (válvula de Bauhin)** | Separa íleo do ceco; esfíncter funcional; previne refluxo de fezes |
| **Ponto de McBurney** | 1/3 lateral da linha EIAS-umbigo; topografia do apêndice |
| **Ampola de Vater (papila duodenal maior)** | 2ª porção duodenal; desembocadura do colédoco + ducto de Wirsung |
| **Esfíncter de Oddi** | Controla saída de bile e suco pancreático; espasmo = dor pós-prandial |
| **Ângulo esplênico do cólon** | Ponto de Griffiths; watershed AMS/AMI; mais vulnerável a isquemia |

---

## 4. Histologia do TGI na Prática — O que Identificar na Lâmina

| Estrutura | Características Histológicas Visíveis |
|-----------|--------------------------------------|
| **Esôfago** | Epitélio estratificado pavimentoso não queratinizado; muscular da mucosa proeminente; glândulas mucosas na submucosa |
| **Estômago (fundo/corpo)** | Glândulas gástricas com células parietais (acidófilas, grandes) e principais (basofílicas, pequenas); fossinhas gástricas |
| **Duodeno** | Glândulas de Brunner na SUBMUCOSA (diferencial único do duodeno) |
| **Jejuno** | Vilosidades mais longas, pregas circulares proeminentes, sem Brunner nem Peyer |
| **Íleo** | Placas de Peyer na SUBMUCOSA; vilosidades menores; células caliciformes mais abundantes |
| **Cólon** | SEM vilosidades; glândulas de Lieberkühn com abundantes células caliciformes (muco); sem pregas circulares |
| **Fígado** | Lóbulos hepáticos (espaço porta na periferia + veia centrolobular ao centro); hepatócitos em cordões; sinusoides |
| **Pâncreas** | Ácinos serosos (escuros, exócrino) + ilhotas de Langerhans (claras, endócrino, sem granulação visível na HE padrão) |

---

## Erros Clássicos em Prova (Uninove)

- **Glândulas de Brunner no jejuno:** Brunner é EXCLUSIVO do DUODENO (diagnóstico histológico). Qualquer lâmina com glândulas submucosas mucosas = duodeno.
- **Placas de Peyer no duodeno:** Peyer está no ÍLEO. Identifica o íleo histologicamente.
- **Cólon sem células caliciformes:** o cólon tem ABUNDANTES células caliciformes (muito muco). O diferencial é não ter vilosidades (ao contrário do delgado).
- **Veia centrolobular = veia porta:** a veia centrolobular fica no CENTRO do lóbulo hepático. A tríade portal (ducto biliar, veia porta e artéria hepática) fica na PERIFERIA.
- **TC: alças de intestino grosso são centrais:** alças de intestino GROSSO ficam na PERIFERIA ("moldura"); intestino delgado no CENTRO da cavidade abdominal.

---

