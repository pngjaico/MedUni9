## Relevância Clínica e Acadêmica

Fígado, vias biliares e pâncreas são órgãos de alta carga de doença no Brasil: hepatite B e C + cirrose, colelitíase (pedra na vesícula), câncer de pâncreas com prognóstico reservado, pancreatite aguda. A anatomia detalhada das vias biliares é a base da cirurgia laparoscópica de vesícula (colecistectomia), e o triângulo de Calot é a área mais perigosa intraoperatoriamente. Para o internato e residência, anatomia cirúrgica do fígado (segmentos de Couinaud) é essencial.

---

## 1. Fígado — Anatomia Geral

### Localização e faces
- **Hipocôndrio direito + epigástrio** (pode se estender ao hipocôndrio esquerdo)
- **Face diafragmática (superior):** convexa; coberta de peritônio exceto área nua (ligamentos coronários)
- **Face visceral (inferior):** em forma de H; sulco sagital direito (vesícula biliar + VCI em fóssas), sulco sagital esquerdo (ligamento redondo + ligamento venoso), sulco transverso = **hilo hepático** (porta hepatis)

### Hilo hepático (porta hepatis) — conteúdo
Mnemônico: **VAN** (Veia porta → Artéria hepática própria → Nervos + linfáticos) - ou simplesmente memorize de posterior para anterior: Veia, Artéria, ducto biliar (bile).

| Estrutura | Posição no hilo |
|-----------|----------------|
| Veia porta | Posterior |
| Artéria hepática própria | Anterior esquerdo |
| Ducto hepático comum | Anterior direito |

---

## 2. Segmentação Hepática de Couinaud

O fígado é dividido em **8 segmentos funcionais** (Couinaud) baseados na distribuição da veia porta e das veias hepáticas — cada segmento é uma unidade cirúrgica independente que pode ser ressecada separadamente.

| Segmento | Localização |
|----------|-------------|
| I | Lobo caudado (posterior) |
| II, III | Lobo esquerdo lateral |
| IV A, IV B | Lobo esquerdo medial |
| V, VI, VII, VIII | Lobo direito |

> Para prova da Uninove, basta saber que existem 8 segmentos de Couinaud e que cada segmento tem vascularização portal e hepática independente.

---

## 3. Vias Biliares

### Vias intra-hepáticas
- Canalículos biliares (entre hepatócitos) → ductos interlobulares → ductos segmentares

### Vias extra-hepáticas
| Estrutura | Detalhes |
|-----------|---------|
| **Ducto hepático direito + esquerdo** | Saem de cada lobo; se unem no hilo |
| **Ducto hepático comum** | Distância da bifurcação até o ducto cístico |
| **Ducto cístico** | Conecta vesícula ao hepático comum; tem válvulas espirais de Heister |
| **Ducto coledoco** | Ducto hepático comum + cístico; desce posteriory ao 1ª parte do duodeno; abre na ampola de Vater (papila duodenal maior na 2ª porção duodenal) |

### Vesícula biliar
- Localizada na fossa cística (face visceral, lobo direito)
- Partes: fundo, corpo, infundíbulo (= bolsa de Hartmann), colo → ducto cístico
- Inervação: plexo celíaco (T7-T9) → dor à direita, pode irradiar para ombro direito (frênico C4)

### Triângulo de Calot (cirúrgico)

| Limite | Estrutura |
|--------|-----------|
| Superior | Ducto hepático comum |
| Inferior | Ducto cístico |
| Lateral | Face inferior do fígado |

**Conteúdo:** artéria cística (ramo da hepática direita, mais constante) — a artéria e ducto que precisam ser clipados e seccionados na colecistectomia.

