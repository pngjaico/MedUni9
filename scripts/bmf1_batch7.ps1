## Ponte com a Clínica

Colecistectomia laparoscópica: o cirurgião identifica o triângulo de Calot, desloca o infundíbulo da vesícula (bolsa de Hartmann) para expor o ducto cístico e a artéria cística, confirma a "visão de segurança crítica" (CVS) com os dois ductos claramente identificados, clipa e secciona. A lesão iatrogênica do ducto biliar principal é a complicação mais temida da colecistectomia laparoscópica — resultando em estenose biliar, icterícia e colangite. Conhecer anatomia das vias biliares e variações do triângulo de Calot é a base da segurança cirúrgica.

