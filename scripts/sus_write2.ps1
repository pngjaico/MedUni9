## 2. Ecomapa

O **ecomapa** representa as relações entre a família e os sistemas externos ao núcleo familiar — comunidade, serviços, trabalho, escola, instituições religiosas.

### Como construir

1. No centro: o núcleo familiar (pode usar o genograma resumido)
2. Ao redor: círculos externos representando sistemas com que a família interage
3. Linhas conectando a família aos sistemas externos indicam a qualidade da relação:

| Tipo de linha | Significado |
|---------------|-------------|
| Linha larga/forte | Relação forte, positiva |
| Linha fina | Relação fraca ou superficial |
| Linha tracejada | Relação frágil ou ocasional |
| Linha com setas | Direção do fluxo de recursos ou energia |
| Linha em zigue-zague | Relação conflituosa ou estressante |

### O que aparece no ecomapa

- Serviços de saúde utilizados (UBS, hospital, CAPS, farmácia)
- Escola / creche
- Trabalho / renda
- Redes de apoio (vizinhos, amigos, religião)
- Programas sociais (CRAS, Bolsa Família)

### Diferença entre genograma e ecomapa

| Aspecto | Genograma | Ecomapa |
|---------|-----------|---------|
| Foco | Estrutura e dinâmica interna familiar | Relações família-comunidade |
| Representação | Gerações e eventos familiares | Sistemas externos e qualidade dos vínculos |
| Objetivo | Identificar padrões e suporte interno | Mapear recursos e estressores externos |
| Gerações | Mínimo 3 | Não se aplica — foco territorial |

