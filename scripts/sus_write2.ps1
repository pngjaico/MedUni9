## 3. Redes de Atenção à Saúde (RAS)

A **RAS** é um conjunto de ações e serviços de saúde articulados em níveis de atenção, integrados por um sistema de referência e contrarreferência, com a APS como coordenadora do cuidado.

### Modelo Matricial das RAS (Mendes, 2011)

| Elemento | Descrição |
|----------|-----------|
| **Centro de comunicação** | Atenção Primária à Saúde — ponto de entrada e coordenação |
| **Pontos de atenção** | UBS, policlínicas, hospitais, CAPS, UPA, etc. |
| **Sistemas de apoio** | Diagnóstico (laboratório, imagem), assistência farmacêutica, TI em saúde (e-SUS) |
| **Governança** | Gestão da rede — Comissão Intergestores Regional (CIR), Bipartite (CIB), Tripartite (CIT) |
| **Modelo assistencial** | Promoção de saúde + vigilância + atenção à demanda espontânea + atenção programada |

### Redes Temáticas Prioritárias

| Rede Temática | Portaria |
|---------------|----------|
| Rede Cegonha (materno-infantil) | Portaria 1.459/2011 |
| Rede de Atenção às Urgências e Emergências (RUE) | Portaria 1.600/2011 |
| Rede de Atenção Psicossocial (RAPS) | Portaria 3.088/2011 |
| Rede de Atenção à Saúde das Pessoas com Doenças Crônicas | Portaria 252/2013 |
| Rede de Cuidados à Pessoa com Deficiência | Portaria 793/2012 |

