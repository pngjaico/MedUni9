## 3. Educação Popular em Saúde

A **Educação Popular em Saúde (EPS)** é uma abordagem político-pedagógica baseada no pensamento de **Paulo Freire**, que propõe a construção coletiva do conhecimento em saúde a partir da realidade e da cultura dos sujeitos.

### Princípios da Educação Popular em Saúde

| Princípio | Descrição |
|-----------|-----------|
| **Diálogo** | O saber popular é reconhecido e integrado ao saber técnico |
| **Horizontalidade** | Não há hierarquia de saber entre profissional e comunidade |
| **Empoderamento (autonomia)** | Comunidade como sujeito ativo na produção de saúde |
| **Participação** | Processo coletivo de decisão sobre as práticas de saúde |
| **Reflexão-ação (práxis)** | Reflexão sobre a realidade seguida de ação transformadora |

### EPS vs. Educação em Saúde Tradicional

| Aspecto | Educação Tradicional | Educação Popular |
|---------|---------------------|-----------------|
| Relação profissional-comunidade | Vertical (especialista ensina) | Horizontal (diálogo) |
| Saber | Técnico-científico predomina | Saber popular é ponto de partida |
| Objetivo | Transmitir informação | Transformar realidade |
| Linguagem | Técnica | Adaptada à cultura local |
| Paulo Freire | Não | Sim — base da metodologia |

### EPS na Prática da ESF

- Grupos de saúde (diabéticos, hipertensos, gestantes) como espaços de construção coletiva
- Território como cenário pedagógico — o agente comunitário facilita EPS na visita domiciliar
- Círculos de cultura (metodologia freiriana) aplicados a temas de saúde
- Rodas de conversa sobre alimentação, violência, direitos em saúde

