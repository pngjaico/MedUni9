## Erros Clássicos em Prova (Uninove)

- **Genograma = árvore genealógica médica simples:** o genograma inclui dinâmica familiar, conflitos e qualidade dos relacionamentos — vai além de apenas listar familiares com doenças.
- **Ecomapa = genograma estendido:** são ferramentas distintas; o ecomapa representa conexões externas à família, não a estrutura interna.
- **EPS é só palestra de promoção de saúde:** educação popular não é transmissão de informação — é processo dialógico que parte do saber da comunidade.
- **Paulo Freire em EPS significa apenas "pedagogia do oprimido":** Paulo Freire desenvolveu uma metodologia (conscientização, tema gerador, círculo de cultura) que é aplicada diretamente nas práticas de EPS no SUS.
- **Genograma precisa ter apenas 2 gerações:** mínimo são 3 gerações (paciente + pais + avós).

