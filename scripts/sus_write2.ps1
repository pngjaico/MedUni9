## Relevância Clínica e Acadêmica

O Pacto em Defesa do SUS é o componente político do Pacto pela Saúde — e o mais frequentemente esquecido pelos estudantes. Enquanto o Pacto pela Vida trata de prioridades clínicas e o Pacto pela Gestão trata de responsabilidades administrativas, o Pacto em Defesa trata da luta continuada para que o SUS exista e seja financiado como política de Estado. A Uninove costuma cobrar essa distinção e os temas de financiamento constitucional em questões sobre controle social e financiamento do SUS.

---

## 1. Pacto em Defesa do SUS — Conceito e Propósito

O Pacto em Defesa do SUS reconhece que o SUS não está consolidado apenas por existir na Constituição — ele precisa ser ativamente defendido contra:

- O subfinanciamento histórico (Brasil gasta em torno de 3,8% do PIB com saúde pública vs. 7-8% de países com cobertura universal real)
- A pressão do setor privado por maior participação/privatização
- A fragmentação das responsabilidades entre entes federativos
- A descredibilização do sistema junto à população

---

## 2. Eixos do Pacto em Defesa do SUS

| Eixo | Descrição |
|------|-----------|
| **Fortalecimento do SUS como política de Estado** | Mobilização social para que o SUS seja tratado como prioridade permanente e não apenas eleitoral |
| **Revisão da Legislação** | Proposta de regulamentação da EC 29/2000 (que definia percentuais mínimos de financiamento em saúde) |
| **Financiamento adequado** | Luta por recursos suficientes do orçamento federal, estadual e municipal |
| **Participação social** | Fortalecimento dos Conselhos e Conferências de Saúde como instâncias deliberativas reais |

---

## 3. Emenda Constitucional 29/2000 e Financiamento do SUS

A **EC 29/2000** foi um marco do Pacto em Defesa do SUS: estabeleceu percentuais mínimos de aplicação em saúde:

| Esfera | Vinculação mínima (EC 29/2000) |
|--------|-------------------------------|
| União | Reajuste da aplicação anterior corrigido pelo PIB nominal |
| Estados e DF | Mínimo de 12% da arrecadação de impostos próprios |
| Municípios | Mínimo de 15% da arrecadação de impostos próprios |

> A regulamentação da EC 29 foi um dos objetivos centrais do Pacto em Defesa. A **Lei Complementar 141/2012** finalmente regulamentou a EC 29, definindo o que conta como "gastos em saúde" para fins do percentual mínimo.

### O que conta como gasto em saúde (LC 141/2012)

| Conta | NÃO conta |
|-------|-----------|
| Atenção à saúde de servidores e dependentes (SUS) | Atenção à saúde de servidores estatutários (Plano de saúde do servidor) |
| Saneamento básico em área não urbanizada | Saneamento básico em área urbanizada |
| Vigilância sanitária e epidemiológica | Pesquisa básica sem vínculo com saúde aplicada |
| Atenção básica, média e alta complexidade | Assistência social |

---

## 4. Controle Social no SUS

O controle social é o mecanismo pelo qual a sociedade civil fiscaliza e influencia a política de saúde. Não é "controle do Estado sobre a sociedade" — é o contrário.

| Instância | Poder | Frequência |
|-----------|-------|------------|
| Conselho Nacional de Saúde (CNS) | Deliberativo — aprova política nacional de saúde | Reunião mensal |
| Conselho Estadual de Saúde (CES) | Deliberativo — aprova política estadual | Reunião mensal |
| Conselho Municipal de Saúde (CMS) | Deliberativo — aprova plano municipal, orçamento, relatório de gestão | Reunião mensal |
| Conferência Nacional de Saúde | Propositivo — avalia e define diretrizes nacionais | A cada 4 anos |

O controle social foi consagrado pela **Lei 8.142/90** como condição para os municípios receberem transferências federais.

