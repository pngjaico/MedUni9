## Relevância Clínica e Acadêmica

O médico de família não trata apenas doenças — trata pessoas dentro de famílias, dentro de comunidades. As ferramentas de abordagem familiar (genograma e ecomapa) são instrumentos práticos que permitem visualizar rapidamente a dinâmica familiar e os recursos disponíveis para o cuidado. A Educação Popular em Saúde é a estratégia para empoderar a comunidade como protora da própria saúde. A Uninove cobra genograma e ecomapa em questões de APS e em casos clínicos que envolvem família, além de perguntar sobre os princípios da Educação Popular.

---

## 1. Genograma

O **genograma** (ou genealograma familiar) é um diagrama que representa graficamente a estrutura de uma família ao longo de, no mínimo, três gerações, incluindo informações sobre saúde, relacionamentos e eventos significativos.

### Símbolos convencionais

| Símbolo | Significado |
|---------|-------------|
| Quadrado | Homem |
| Círculo | Mulher |
| Triângulo | Criança de sexo não definido / aborto |
| X sobre símbolo | Pessoa falecida |
| Linha horizontal entre dois símbolos | União (casamento ou união estável) |
| Linha vertical descendente | Filho/filha |
| Linha dupla horizontal | Casamento consanguíneo |
| Linhas onduladas | Relacionamento conflituoso |

### Informações incluídas no genograma

- Nome, idade ou data de nascimento de cada membro
- Doenças e causas de morte relevantes
- Eventos familiares significativos (divórcio, migrações, traumas)
- Ao menos 3 gerações (paciente identificado + pais + avós)

### Para que serve

- Identificar padrões hereditários de doenças (DM, HAS, CA, doenças genéticas)
- Avaliar dinâmica familiar e recursos de apoio
- Planejar abordagens preventivas baseadas no risco familiar
- Identificar quem cuida de quem na família (cuidador principal)

