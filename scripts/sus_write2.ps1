## Relevância Clínica e Acadêmica

A Atenção Primária à Saúde (APS) é o nível de atenção em que você passará a maior parte da sua residência de Medicina de Família e Comunidade — e onde 80% dos problemas de saúde da população deveriam ser resolvidos. A PNAB (Política Nacional de Atenção Básica) e a Estratégia Saúde da Família (ESF) são os instrumentos operacionais dessa lógica. A Uninove cobra a equipe mínima da ESF, os atributos da APS de Starfield e as responsabilidades do médico de família com frequência em provas e em casos clínicos.

---

## 1. Atenção Primária à Saúde — Atributos (Starfield, 1992)

**Barbara Starfield** sistematizou os atributos essenciais e derivados da APS:

### Atributos Essenciais

| Atributo | Definição |
|----------|-----------|
| **Acesso de primeiro contato (Acessibilidade)** | APS como porta de entrada preferencial para novos problemas de saúde |
| **Longitudinalidade** | Cuidado contínuo ao longo do tempo com o mesmo profissional/equipe; vínculo |
| **Integralidade** | Atenção a todos os problemas de saúde do indivíduo — preventivo, curativo e reabilitador |
| **Coordenação do cuidado** | APS coordena e integra o cuidado entre diferentes pontos da RAS |

### Atributos Derivados

| Atributo | Definição |
|----------|-----------|
| **Orientação familiar** | Considera a família como unidade de cuidado |
| **Orientação comunitária** | Considera o território, contexto social e comunitário |
| **Competência cultural** | Reconhece e respeita diferenças culturais no cuidado à saúde |

---

## 2. PNAB — Política Nacional de Atenção Básica

A **PNAB** é a principal normativa que regulamenta a APS no Brasil. A versão vigente é a **PNAB 2017** (Portaria 2.436/17), que substituiu a PNAB 2011.

### Principais mudanças da PNAB 2017

| Aspecto | PNAB 2011 | PNAB 2017 |
|---------|-----------|-----------|
| Equipe mínima ESF (médico) | 1 médico por equipe | 1 médico (pode ser generalista ou especialista em MFC) |
| NASF | NASF-AB com composição específica | Equipe Multiprofissional de APS (eMulti) — mais flexível |
| Cobertura para financiamento diferenciado | ESF era preferencial | ESF e Atenção Básica Tradicional recebem |
| Número de pessoas por equipe | 2.000 a 3.500 | 2.000 a 3.500 (mantido) |

---

## 3. Estratégia Saúde da Família (ESF)

A **ESF** é a principal estratégia de reorganização da APS no Brasil. Iniciada como PACS em 1991 e como PSF em 1994, tornou-se estratégia (não programa) a partir de 2006.

### Equipe Mínima da ESF

| Profissional | Quantidade |
|--------------|------------|
| Médico (generalista ou especialista em APS) | 1 |
| Enfermeiro | 1 |
| Técnico/auxiliar de enfermagem | 2 a 3 |
| Agente Comunitário de Saúde (ACS) | Mínimo 1 para cada 150 famílias / máx. 750 pessoas |

> **Área de cobertura:** cada equipe ESF é responsável por 2.000 a 3.500 pessoas (famílias cadastradas no território).

### Atribuições do Médico na ESF (PNAB 2017)

- Realizar consultas clínicas, incluindo atendimento de urgência/emergência
- Realizar atividades em grupo e de educação em saúde
- Solicitar exames complementares e prescrever medicamentos da RENAME
- Encaminhar para outros pontos da RAS quando necessário
- Participar das reuniões de equipe
- Realizar visitas domiciliares

---

## 4. Agente Comunitário de Saúde (ACS)

O **ACS** é o elo entre a comunidade e a equipe de saúde. Deve **morar na comunidade** que atende (requisito obrigatório desde a Lei 11.350/2006).

| Atividade | Realiza? |
|-----------|----------|
| Cadastramento das famílias | Sim |
| Visita domiciliar | Sim (mínimo 1/mês para cada família) |
| Monitoramento de situações de risco | Sim |
| Prescrição de medicamentos | Não |
| Realização de curativos | Não (ação de técnico de enfermagem) |

---

## 5. Cobertura da ESF no Brasil

A ESF atingiu cobertura superior a 60% da população brasileira. É a estratégia com maior impacto documentado na redução da mortalidade infantil e na hospitalização por condições sensíveis à APS (ICSAP).

---

## Erros Clássicos em Prova (Uninove)

- **ACS não precisa morar na área:** errado — é requisito legal; o ACS deve ser morador da comunidade que atende.
- **Integralidade no Starfield = mesmo que integralidade da Lei 8.080:** cuidado — Starfield usa integralidade como reconhecer e responder a todos os problemas de saúde do indivíduo; na Lei 8.080 é mais amplo (promoção + proteção + reabilitação; individual + coletivo).
- **Longitudinalidade é o mesmo que continuidade:** longitudinalidade inclui vínculo e conhecimento ao longo do tempo; continuidade pode ser apenas dar sequência a um tratamento sem vínculo.
- **A ESF cobre até 5.000 pessoas:** errado — o teto é 3.500 (com território de alto risco, até 4.000 em alguns contextos, mas o padrão é 2.000-3.500).
- **NASF substitui a equipe ESF:** o NASF (ou eMulti na PNAB 2017) apoia e complementa a equipe ESF — não a substitui.

