## Relevância Clínica e Acadêmica

O Pacto pela Gestão define qual esfera de governo faz o quê dentro do SUS. Sem essa divisão clara, o sistema colapsa: municípios pequenos não conseguem oferecer especialidades, e os grandes ficam sobrecarregados com pacientes de outros municípios. A Rede de Atenção à Saúde (RAS) e a regionalização são as respostas estruturais a esse problema. A Uninove cobra o Decreto 7508/2011, o conceito de Região de Saúde e os componentes das redes temáticas em questões de gestão e organização do SUS.

