## 1. Pacto pela Gestão

O Pacto pela Gestão (Portaria GM/MS 399/2006, mesmo documento do Pacto pela Vida) define as responsabilidades sanitárias de cada ente federativo no SUS.

### Responsabilidades por esfera

| Esfera | Responsabilidades principais |
|--------|------------------------------|
| **União** | Formulação de política nacional; financiamento federal; vigilância sanitária/epidemiológica nacional; regulação do setor |
| **Estado** | Formulação da política estadual; financiamento estadual; coordenação das Regiões de Saúde; regulação da média e alta complexidade |
| **Município** | Execução das ações de saúde; Atenção Básica; gestão das UBS e ESF; vigilância sanitária local |

### Instrumentos de gestão

| Instrumento | Finalidade |
|-------------|------------|
| Termo de Compromisso de Gestão (TCG) | Substitui habilitação; formaliza responsabilidades e metas |
| Plano de Saúde | Planejamento de 4 anos; base para o orçamento da saúde |
| Relatório de Gestão | Prestação de contas anual; condição para receber transferências |
| Programação Pactuada e Integrada (PPI) | Pactuação de fluxos de referência entre municípios |

