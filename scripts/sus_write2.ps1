## 2. Decreto 7508/2011 — Regulamentação da Lei 8.080

O Decreto 7.508/2011 é o marco normativo mais importante para organização atual do SUS. Regulamentou temas que a Lei 8.080 não havia detalhado:

- **Região de Saúde:** espaço geográfico contínuo de municípios que compartilham identidade cultural, econômica e de rede de serviços
- **Contrato Organizativo de Ação Pública da Saúde (COAP):** substitui o TCG como instrumento de pactuação; integra responsabilidades dos três entes
- **Relação Nacional de Ações e Serviços de Saúde (RENASES):** define o escopo de obrigações do SUS
- **Relação Nacional de Medicamentos (RENAME):** lista os medicamentos fornecidos pelo SUS

### Região de Saúde — componentes mínimos

Para ser reconhecida como Região de Saúde, a área deve contar com:
1. Atenção Primária à Saúde
2. Urgência e Emergência
3. Atenção Psicossocial
4. Atenção Ambulatorial Especializada e Hospitalar
5. Vigilância em Saúde

